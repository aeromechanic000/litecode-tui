#[derive(Parser, Debug)]
#[command(
    name = "litepilot",
    version,
    about = "Terminal AI coding assistant powered by local Ollama models"
)]
struct Args {
    /// Working directory (defaults to current directory)
    #[arg(short, long)]
    dir: Option<String>,
    /// Resume a previous session (latest, or by ID)
    #[arg(long)]
    resume: Option<Option<String>>,
    /// List saved sessions
    #[arg(long)]
    sessions: bool,
    /// Non-interactive (headless) mode: run one prompt, stream output to stdout, exit.
    /// Files generated by the model are written automatically.
    #[arg(short, long, value_name = "PROMPT")]
    prompt: Option<String>,
}

fn main() -> Result<()> {
    let args = Args::parse();

    // Install crash dump handler early
    install_crash_handler();

    // Determine workspace
    let workspace = match args.dir {
        Some(ref d) => PathBuf::from(d),
        None => std::env::current_dir()?,
    };

    // Handle --sessions: list and exit
    if args.sessions {
        match session::persistence::list_sessions() {
            Ok(sessions) if sessions.is_empty() => {
                println!("No saved sessions.");
            }
            Ok(sessions) => {
                println!("Saved sessions:\n");
                for s in &sessions {
                    println!(
                        "  {}  ({} messages)  {}",
                        &s.id[..8],
                        s.message_count,
                        s.preview
                    );
                    println!("    created: {}  updated: {}", s.created_at, s.updated_at);
                }
            }
            Err(e) => eprintln!("Error listing sessions: {}", e),
        }
        return Ok(());
    }

    // Setup config — use project-local .litepilot if present, else global ~/.litepilot
    let litepilot_dir = config::Config::ensure_dirs_for(&workspace)?;
    let config = config::Config::load_for_workspace(&workspace).unwrap_or_else(|_| {
        let default = config::Config::default();
        let _ = default.save(&litepilot_dir.join("config.toml"));
        default
    });

    // Initialize file logging (guard must live until app exits)
    let _log_guard = logger::init(&litepilot_dir);

    tracing::info!(
        "LitePilot v{} starting | workspace={} | endpoint={}",
        env!("CARGO_PKG_VERSION"),
        workspace.display(),
        config.ollama_endpoint
    );
    tracing::info!(
        "models: plan={} exec={} eval={}",
        config.effective_plan_model(),
        config.exec_model,
        config.effective_eval_model()
    );
    tracing::info!("mode: {}", config.default_mode);

    // Headless (-p) branch: skip TUI + wizard, run one prompt and exit.
    if let Some(prompt) = args.prompt.clone() {
        let resume_session = load_resume_session(&args.resume);
        return run_headless(config, workspace, resume_session, prompt);
    }

    // Setup terminal — fullscreen for wizard
    enable_raw_mode()?;
    let mut stdout = io::stdout();
    crossterm::execute!(stdout, EnterAlternateScreen)?;
    let backend = CrosstermBackend::new(stdout);
    let mut terminal = Terminal::new(backend)?;

    // Run setup wizard — user confirms or changes Ollama URL and model selection
    let config = wizard::run(&mut terminal, config, &workspace)?;

    // Switch from fullscreen wizard to inline terminal for main app
    crossterm::execute!(terminal.backend_mut(), LeaveAlternateScreen)?;
    drop(terminal);
    let backend = CrosstermBackend::new(io::stdout());
    let mut terminal = Terminal::with_options(backend, TerminalOptions {
        viewport: Viewport::Inline(3),
    })?;

    // Load session if --resume was specified
    let resume_session = load_resume_session(&args.resume);

    // Run app with panic recovery to ensure terminal is restored
    let result = std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| {
        run_app(&mut terminal, config, workspace, resume_session)
    }));

    tracing::info!("session ended");

    // Restore terminal (even if panic occurred)
    disable_raw_mode()?;
    terminal.show_cursor()?;

    match result {
        Ok(inner) => inner,
        Err(panic_payload) => {
            let msg = if let Some(s) = panic_payload.downcast_ref::<&str>() {
                s.to_string()
            } else if let Some(s) = panic_payload.downcast_ref::<String>() {
                s.clone()
            } else {
                "unknown panic".to_string()
            };
            tracing::error!("fatal panic: {}", msg);
            eprintln!("Fatal error: {}", msg);
            std::process::exit(1);
        }
    }
}

/// Resolve `--resume` (None | latest | by-id-prefix) to a Session, if any.
fn load_resume_session(resume: &Option<Option<String>>) -> Option<session::Session> {
    match resume {
        Some(Some(id)) => match session::persistence::load_session(id) {
            Ok(s) => {
                tracing::info!(
                    "resuming session {} ({} messages)",
                    &s.id[..8],
                    s.messages.len()
                );
                Some(s)
            }
            Err(e) => {
                tracing::warn!("failed to load session {}: {}", id, e);
                None
            }
        },
        Some(None) => match session::persistence::list_sessions() {
            Ok(sessions) if !sessions.is_empty() => {
                let latest = &sessions[0];
                match session::persistence::load_session(&latest.id) {
                    Ok(s) => {
                        tracing::info!(
                            "resuming latest session {} ({} messages)",
                            &s.id[..8],
                            s.messages.len()
                        );
                        Some(s)
                    }
                    Err(_) => None,
                }
            }
            _ => None,
        },
        None => None,
    }
}

/// Headless entry point: no TUI, no wizard. Runs one prompt through the same
/// plan→execute pipeline as the interactive app, streams the response to stdout,
/// writes any files the model produces (Auto semantics — headless has no
/// confirmation surface), then exits.
fn run_headless(
    config: config::Config,
    workspace: PathBuf,
    resume_session: Option<session::Session>,
    prompt: String,
) -> Result<()> {
    if config.exec_model.is_empty() {
        eprintln!(
            "No exec_model configured. Run `litepilot` once interactively to set up, \
             or edit {}",
            config::Config::config_path_for(&workspace).display()
        );
        std::process::exit(2);
    }

    // Headless has no confirmation surface → force Auto mode for writes.
    let mut cfg = config;
    cfg.default_mode = "auto".into();

    let mut app_state = AppState::new(cfg, workspace.clone());

    // Replay resumed history into the conversation (used by the planner/executor
    // for context).
    if let Some(session) = resume_session.as_ref() {
        for msg in &session.messages {
            app_state.conversation_history.push(ConversationMessage {
                role: msg.role.clone(),
                content: msg.content.clone(),
                tokens: util::text::estimate_tokens(&msg.content),
            });
        }
        app_state.current_session = session.clone();
        eprintln!(
            "[resumed session {} — {} messages]",
            &session.id[..8],
            session.messages.len()
        );
    }

    app_state.event_sink.turn_started(
        &app_state.config.exec_model,
        "HEADLESS",
        prompt.len(),
    );

    // Connectivity check before we spawn anything.
    {
        let endpoint = app_state.config.ollama_endpoint.clone();
        let ping_cfg = config::Config {
            ollama_endpoint: endpoint,
            ..config::Config::default()
        };
        let rt = tokio::runtime::Runtime::new()?;
        let ok = rt.block_on(async move {
            match ollama::OllamaClient::new(&ping_cfg) {
                Ok(c) => c.ping().await.is_ok(),
                Err(_) => false,
            }
        });
        if !ok {
            eprintln!(
                "Cannot connect to Ollama at {}. Start Ollama first.",
                app_state.config.ollama_endpoint
            );
            std::process::exit(1);
        }
    }

    println!(
        "[litepilot -p | model={} | workspace={}]",
        app_state.config.exec_model,
        app_state.workspace.display()
    );
    println!(">>> {}", prompt);
    println!("---");

    // Record the user turn.
    app_state.conversation_history.push(ConversationMessage {
        role: "user".into(),
        content: prompt.clone(),
        tokens: util::text::estimate_tokens(&prompt),
    });
    app_state.current_session.add_message("user", &prompt);

    // Update prompt builder volatile layers, same as the interactive path.
    app_state
        .prompt_builder
        .update_environment(prompt::EnvironmentBlock::capture(&app_state.workspace));
    app_state
        .prompt_builder
        .set_volatile(app_state.working_set.summary(), app_state.conversation_summary.clone());
    app_state.prompt_builder.set_current_goal(&prompt);

    if let Err(e) = app_state.snapshot_manager.pre_turn(&prompt) {
        tracing::debug!("pre-turn snapshot skipped: {}", e);
    }

    let (tx, rx) = mpsc::channel::<agent::retry::PipelineResult>();
    let client = ollama::OllamaClient::new(&app_state.config)?;
    spawn_plan_then_execute(&app_state, &client, &prompt, tx.clone());
    // Drop our local sender so the channel closes once all background work finishes.
    // (Background threads hold their own clones; when they exit, rx.recv() returns Err.)
    drop(client);

    // Drain pipeline events and print to stdout. Completion is signaled by either:
    //   - all plan steps completed (count StreamDone events vs total from StepStart),
    //   - the single-step fallback (no StepStart → first StreamDone completes),
    //   - or the channel closing (background thread exited).
    let mut done = false;
    let mut expected_steps: Option<usize> = None;
    let mut completed_steps = 0;
    while !done {
        let result = match rx.recv() {
            Ok(r) => r,
            Err(_) => {
                // All senders dropped — pipeline finished.
                break;
            }
        };
        match result {
            agent::retry::PipelineResult::PlanReady { plan } => {
                if plan.starts_with("(plan unavailable") {
                    eprintln!("[plan unavailable — executing directly]");
                } else {
                    println!("{}", plan);
                    println!("---");
                }
                // Headless = Auto semantics: auto-execute the plan.
                app_state.last_plan = Some(plan.clone());
                spawn_execution_with_plan(&app_state, &prompt, &plan, tx.clone());
            }
            agent::retry::PipelineResult::StepStart {
                step,
                total,
                description,
            } => {
                if step == 1 {
                    eprintln!("◆ Exec");
                }
                eprintln!("[step {}/{}] {}", step, total, description);
                if expected_steps.is_none() {
                    expected_steps = Some(total);
                    completed_steps = 0;
                }
            }
            agent::retry::PipelineResult::StreamChunk { content } => {
                let sanitized = agent::tools_parser::sanitize_output(&content);
                print!("{}", sanitized);
                use std::io::Write;
                let _ = std::io::stdout().flush();
            }
            agent::retry::PipelineResult::StreamDone { content, tool_log } => {
                let sanitized = agent::tools_parser::sanitize_output(&content);
                println!();
                println!("---");

                // Apply file changes (Auto mode) — exec content is the file source.
                let changes = agent::parse_file_changes(&sanitized);
                if !changes.is_empty() {
                    apply_headless_changes(&mut app_state, &changes, &tx);
                }

                completed_steps += 1;
                let reached_total = expected_steps
                    .map(|t| completed_steps >= t)
                    .unwrap_or(true);

                // Stash exec context for the eval step.
                app_state.last_exec_output = Some(sanitized.clone());
                app_state.last_exec_tool_log = Some(tool_log.clone());
                app_state.last_user_request = Some(prompt.clone());

                // Eval runs when there is anything to reflect on — assistant text OR
                // tool results (a tool-only step may have empty prose but a real
                // answer in the tool log).
                let eval_will_run = reached_total
                    && (!sanitized.is_empty() || !tool_log.is_empty())
                    && !app_state.config.eval_model.is_empty();
                if eval_will_run {
                    // Eval reflection owns the final answer; EvalReady finalizes.
                    println!("◆ Eval");
                    spawn_eval_reflection(
                        &app_state,
                        &prompt,
                        app_state.last_plan.as_deref().unwrap_or(""),
                        &sanitized,
                        &tool_log,
                        app_state.redo_count,
                        tx.clone(),
                    );
                } else {
                    // Short-circuit (single-model / empty): exec content is the answer.
                    commit_assistant_answer(&mut app_state, &sanitized, &tx);
                    if reached_total {
                        if let Err(e) = app_state.snapshot_manager.post_turn("headless") {
                            tracing::debug!("post-turn snapshot skipped: {}", e);
                        }
                        done = true;
                    }
                }
            }
            agent::retry::PipelineResult::StreamMeta { .. } => {
                // KV-cache stats — not relevant for headless output.
            }
            agent::retry::PipelineResult::ToolStart { tool_name, .. } => {
                eprintln!("[tool] {} ...", tool_name);
            }
            agent::retry::PipelineResult::ToolResultReady { result } => {
                if result.success {
                    let preview: String = result.output.chars().take(300).collect();
                    eprintln!(
                        "[tool] {} done: {}{}",
                        result.tool_name,
                        preview,
                        if result.output.len() > 300 { "..." } else { "" }
                    );
                } else {
                    eprintln!("[tool] {} failed: {}", result.tool_name, result.output);
                }
            }
            agent::retry::PipelineResult::DiagnosticReady { result: diag } => {
                if diag.has_errors() {
                    for err in &diag.errors {
                        let loc = match err.line {
                            Some(l) => format!("{}:{}", err.file, l),
                            None => err.file.clone(),
                        };
                        eprintln!("[diagnostic] {} — {}", loc, err.message);
                    }
                }
            }
            agent::retry::PipelineResult::EvalReady { verdict, .. } => {
                let summary = if verdict.summary.trim().is_empty() {
                    app_state.last_exec_output.clone().unwrap_or_default()
                } else {
                    agent::tools_parser::sanitize_output(&verdict.summary)
                };
                println!();
                println!("{}", summary);
                commit_assistant_answer(&mut app_state, &summary, &tx);
                if let Some(p) = &verdict.proposal {
                    eprintln!(
                        "[eval] result may be incomplete ({}): {} \
                         — non-interactive; rerun with more detail if needed.",
                        match p.kind {
                            agent::retry::RedoKind::Further => "further round",
                            agent::retry::RedoKind::Plan => "re-plan",
                            agent::retry::RedoKind::None => "none",
                        },
                        p.reason
                    );
                }
                if let Err(e) = app_state.snapshot_manager.post_turn("headless") {
                    tracing::debug!("post-turn snapshot skipped: {}", e);
                }
                done = true;
            }
            agent::retry::PipelineResult::Status { message } => {
                eprintln!("{}", message);
            }
            agent::retry::PipelineResult::SummaryReady { .. } => {
                // Compaction notice — not surfaced in headless mode.
            }
            agent::retry::PipelineResult::SearchDone { count, .. } => {
                eprintln!("[search] {} result(s)", count);
            }
            agent::retry::PipelineResult::Retry(r) => {
                // Non-streaming fallback path — print and finish.
                let content = match r {
                    agent::retry::RetryResult::Success { content, .. } => content,
                    agent::retry::RetryResult::Exhausted {
                        content, attempts, ..
                    } => {
                        eprintln!("[exhausted {} retries]", attempts);
                        content
                    }
                    agent::retry::RetryResult::Failed { last_error, .. } => {
                        eprintln!("[failed] {}", last_error);
                        done = true;
                        continue;
                    }
                };
                let sanitized = agent::tools_parser::sanitize_output(&content);
                println!("{}", sanitized);
                let changes = agent::parse_file_changes(&sanitized);
                if !changes.is_empty() {
                    apply_headless_changes(&mut app_state, &changes, &tx);
                }
                app_state.conversation_history.push(ConversationMessage {
                    role: "assistant".into(),
                    content: sanitized.clone(),
                    tokens: 0,
                });
                app_state.current_session.add_message("assistant", &sanitized);
                let _ = session::persistence::save_session(&app_state.current_session);
                done = true;
            }
        }
    }

    // Drain any trailing events (diagnostics, eval) with a short timeout.
    while let Ok(result) = rx.recv_timeout(std::time::Duration::from_millis(500)) {
        match result {
            agent::retry::PipelineResult::DiagnosticReady { result: diag } => {
                if diag.has_errors() {
                    for err in &diag.errors {
                        let loc = match err.line {
                            Some(l) => format!("{}:{}", err.file, l),
                            None => err.file.clone(),
                        };
                        eprintln!("[diagnostic] {} — {}", loc, err.message);
                    }
                }
            }
            agent::retry::PipelineResult::EvalReady { verdict, .. } => {
                println!();
                println!("{}", verdict.summary);
                if let Some(p) = &verdict.proposal {
                    eprintln!("[eval] proposal: {}", p.reason);
                }
            }
            _ => {}
        }
    }

    Ok(())
}

/// Apply file changes detected from the model output to disk (headless Auto path).
fn apply_headless_changes(
    app_state: &mut AppState,
    changes: &[agent::FileChange],
    tx: &mpsc::Sender<agent::retry::PipelineResult>,
) {
    let sandbox = sandbox::Sandbox::new(app_state.workspace.clone());
    let file_ops = project::file_ops::FileOps::new(&sandbox, app_state.mode);

    let mut written: Vec<std::path::PathBuf> = Vec::new();
    for change in changes {
        let full_path = app_state.workspace.join(&change.path);
        let fc = match if change.action == "delete" {
            file_ops.prepare_delete(&full_path)
        } else {
            file_ops.prepare_write(&full_path, &change.content)
        } {
            Ok(fc) => fc,
            Err(e) => {
                eprintln!("[blocked] {}: {}", change.path.display(), e);
                continue;
            }
        };
        match file_ops.apply_change(&fc) {
            Ok(()) => {
                println!(
                    "  {} {}",
                    if change.action == "delete" {
                        "Deleted"
                    } else {
                        "Wrote"
                    },
                    change.path.display()
                );
                if change.action != "delete" {
                    written.push(full_path);
                }
            }
            Err(e) => {
                eprintln!(
                    "[failed] {} {}: {}",
                    change.action,
                    change.path.display(),
                    e
                );
            }
        }
    }

    if !written.is_empty() {
        let tx = tx.clone();
        let workspace = app_state.workspace.clone();
        std::thread::spawn(move || {
            let rt = match tokio::runtime::Runtime::new() {
                Ok(rt) => rt,
                Err(_) => return,
            };
            let sandbox = sandbox::Sandbox::new(workspace);
            let result = rt.block_on(async {
                agent::diagnostics::run_diagnostics(&written, &sandbox).await
            });
            let _ = tx.send(agent::retry::PipelineResult::DiagnosticReady { result });
        });
    }
}

fn run_app(
    terminal: &mut Terminal<CrosstermBackend<io::Stdout>>,
    config: config::Config,
    workspace: PathBuf,
    resume_session: Option<session::Session>,
) -> Result<()> {
    let mut ui_state = ui::UiState::from_config(&config).with_workspace(workspace.clone());
    let mut app_state = AppState::new(config, workspace);

    // Resume session if provided
    if let Some(session) = resume_session {
        for msg in &session.messages {
            match msg.role.as_str() {
                "user" => ui_state.add_output(OutputLine::User(msg.content.clone())),
                "assistant" => ui_state.add_output(OutputLine::Assistant(msg.content.clone())),
                "system" => ui_state.add_output(OutputLine::System(msg.content.clone())),
                _ => {}
            }
        }
        app_state.current_session = session;
        ui_state.add_output(OutputLine::System(format!(
            "Resumed session {} ({} messages)",
            &app_state.current_session.id[..8],
            app_state.current_session.messages.len()
        )));
    }

    // Welcome banner
    let version = env!("CARGO_PKG_VERSION");
    let banner = format!(
        "version: {v:<6} \n\
        ╔═════════════════════════════════════════════════╗\n\
        ║      _      _ _       ____  _ _       _         ║\n\
        ║     | |    (_) |_ ___|  _ \\(_) | ___ | |_       ║\n\
        ║     | |    | | __/ _ \\ |_) | | |/ _ \\| __|      ║\n\
        ║     | |____| | ||  __/  __/| | | (_) | |_       ║\n\
        ║     |______|_|\\__\\___|_|   |_|_|\\___/ \\__|      ║\n\
        ║                                                 ║\n\
        ║     Ollama-powered AI assistant in Teminal      ║\n\
        ╚═════════════════════════════════════════════════╝",
        v = version
    );
    ui_state.add_output(OutputLine::System(banner));
    ui_state.add_output(OutputLine::System(
        "Shift+Tab: mode | Enter: send | Shift+Enter: newline | Ctrl+Tab: think | Ctrl+C: quit | /skills: list skills".into(),
    ));

    // Show loaded skills count
    let skill_count = app_state.skills.list().len();
    if skill_count > 0 {
        let names: Vec<&str> = app_state
            .skills
            .list()
            .iter()
            .map(|s| s.name.as_str())
            .collect();
        ui_state.add_output(OutputLine::System(format!(
            "Loaded {} skills: /{}",
            skill_count,
            names.join(", /")
        )));
    }

    let ollama_client = ollama::OllamaClient::new(&app_state.config)?;

    // Check Ollama connectivity in background
    let endpoint = app_state.config.ollama_endpoint.clone();
    let ping_result = std::thread::spawn(move || {
        let rt = tokio::runtime::Runtime::new()?;
        rt.block_on(async {
            let client = ollama::OllamaClient::new(&config::Config {
                ollama_endpoint: endpoint,
                ..config::Config::default()
            })?;
            client.ping().await
        })
    });

    if let Ok(Ok(_)) = ping_result.join() {
        tracing::info!("ollama ping OK: {}", app_state.config.ollama_endpoint);
        ui_state.add_output(OutputLine::System(format!(
            "Connected to Ollama at {}",
            app_state.config.ollama_endpoint
        )));
        ui_state.add_output(OutputLine::System(format!(
            "[Plan]:{} [Exec]:{} [Eval]:{}",
            app_state.config.effective_plan_model(),
            app_state.config.exec_model,
            app_state.config.effective_eval_model()
        )));
    } else {
        tracing::error!("ollama ping FAILED: {}", app_state.config.ollama_endpoint);
        ui_state.add_output(OutputLine::Error(format!(
            "Cannot connect to Ollama at {}. Start Ollama first.",
            app_state.config.ollama_endpoint
        )));
    }

    // Channel for receiving LLM results from background threads
    let (result_tx, result_rx) = mpsc::channel::<agent::retry::PipelineResult>();

    // Warm up models for residency if configured
    if app_state.config.keep_exec_resident() || app_state.config.keep_eval_resident() {
        let warmup_config = app_state.config.clone();
        let warmup_tx = result_tx.clone();
        std::thread::spawn(move || {
            let rt = match tokio::runtime::Runtime::new() {
                Ok(rt) => rt,
                Err(e) => {
                    tracing::error!("warmup runtime error: {}", e);
                    return;
                }
            };
            let client = match ollama::OllamaClient::new(&warmup_config) {
                Ok(c) => c,
                Err(e) => {
                    tracing::error!("warmup client error: {}", e);
                    return;
                }
            };

            let mut warmed = Vec::new();
            if warmup_config.keep_exec_resident() && !warmup_config.exec_model.is_empty() {
                let model = warmup_config.exec_model.clone();
                let _ = warmup_tx.send(agent::retry::PipelineResult::Status {
                    message: format!("[Residency] Warming up exec model: {}...", model),
                });
                match rt.block_on(client.warmup_model(&model)) {
                    Ok(()) => warmed.push(model.clone()),
                    Err(e) => {
                        let _ = warmup_tx.send(agent::retry::PipelineResult::Status {
                            message: format!("[Residency] Failed to warm up exec model '{}': {}", model, e),
                        });
                    }
                }
            }
            if warmup_config.keep_eval_resident() {
                let model = warmup_config.eval_model.clone();
                let _ = warmup_tx.send(agent::retry::PipelineResult::Status {
                    message: format!("[Residency] Warming up eval model: {}...", model),
                });
                match rt.block_on(client.warmup_model(&model)) {
                    Ok(()) => warmed.push(model.clone()),
                    Err(e) => {
                        let _ = warmup_tx.send(agent::retry::PipelineResult::Status {
                            message: format!("[Residency] Failed to warm up eval model '{}': {}", model, e),
                        });
                    }
                }
            }
            if warmup_config.keep_plan_resident() {
                let model = warmup_config.plan_model.clone();
                let _ = warmup_tx.send(agent::retry::PipelineResult::Status {
                    message: format!("[Residency] Warming up plan model: {}...", model),
                });
                match rt.block_on(client.warmup_model(&model)) {
                    Ok(()) => warmed.push(model.clone()),
                    Err(e) => {
                        let _ = warmup_tx.send(agent::retry::PipelineResult::Status {
                            message: format!("[Residency] Failed to warm up plan model '{}': {}", model, e),
                        });
                    }
                }
            }
            if !warmed.is_empty() {
                let _ = warmup_tx.send(agent::retry::PipelineResult::Status {
                    message: format!("[Residency] Models pinned: {}", warmed.join(", ")),
                });
            }
        });
    }

    loop {
        // Flush pending output above the viewport via insert_before()
        flush_pending_output(terminal, &mut ui_state)?;

        // Render the inline viewport (status + activity + input)
        terminal.draw(|f| ui::draw(f, &app_state, &mut ui_state))?;

        // Check for completed LLM responses (non-blocking)
        while let Ok(result) = result_rx.try_recv() {
            match result {
                agent::retry::PipelineResult::Retry(r) => {
                    app_state.is_processing = false;
                    ui_state.stop_thinking();
                    // Emit structured completion event
                    match &r {
                        agent::retry::RetryResult::Success { content, attempts } => {
                            app_state.event_sink.turn_complete(
                                &app_state.config.exec_model,
                                content.len(),
                                *attempts,
                                0,
                                0,
                            );
                        }
                        agent::retry::RetryResult::Exhausted {
                            content, attempts, ..
                        } => {
                            app_state.event_sink.turn_complete(
                                &app_state.config.exec_model,
                                content.len(),
                                *attempts,
                                0,
                                0,
                            );
                        }
                        agent::retry::RetryResult::Failed {
                            last_error,
                            attempts,
                        } => {
                            app_state
                                .event_sink
                                .emit(&hooks::HookEvent::error(last_error, "retry"));
                            let _ = attempts; // used above
                        }
                    }
                    match &r {
                        agent::retry::RetryResult::Success { content, attempts } => {
                            tracing::info!(
                                "llm response: {} bytes (attempts={})",
                                content.len(),
                                attempts
                            );
                        }
                        agent::retry::RetryResult::Exhausted {
                            content,
                            attempts,
                            corrections,
                        } => {
                            tracing::warn!(
                                "llm response exhausted retries: attempts={}, corrections={}",
                                attempts,
                                corrections.len()
                            );
                            tracing::info!("llm response content: {} bytes", content.len());
                        }
                        agent::retry::RetryResult::Failed {
                            last_error,
                            attempts,
                        } => {
                            tracing::error!(
                                "llm failed after {} attempts: {}",
                                attempts,
                                last_error
                            );
                        }
                    }
                    render_retry_result(&mut ui_state, r);
                    ui_state.add_output(OutputLine::Separator);
                }
                agent::retry::PipelineResult::SearchDone { count, .. } => {
                    // Intermediate status — LLM still running
                    tracing::info!("web search: {} results", count);
                    ui_state.add_output(OutputLine::System(format!(
                        "[search] Found {} result(s)",
                        count
                    )));
                    continue; // Don't drain queue yet
                }
                agent::retry::PipelineResult::StreamChunk { content } => {
                    // Remove thinking indicator on first chunk
                    ui_state.stop_thinking();
                    // Sanitize forged tool call markers before display
                    let sanitized = agent::tools_parser::sanitize_output(&content);
                    // Append chunk to streaming output — don't mark processing done
                    ui_state.append_stream_chunk(&sanitized);
                    continue;
                }
                agent::retry::PipelineResult::StreamDone { content, tool_log } => {
                    ui_state.stop_thinking();
                    ui_state.finish_stream();
                    // Sanitize output for display.
                    let content = agent::tools_parser::sanitize_output(&content);
                    tracing::info!("stream complete: {} bytes", content.len());
                    if content.len() < 100 {
                        tracing::warn!(
                            "suspiciously short response ({} bytes): {:?}",
                            content.len(),
                            content
                        );
                    } else {
                        tracing::debug!("stream content (first 500 chars): {:.500}", content);
                    }

                    // Stash exec context for the eval step + redo loop.
                    app_state.last_exec_output = Some(content.clone());
                    app_state.last_exec_tool_log = Some(tool_log.clone());
                    // Preserve the ORIGINAL user request across redos so a "plan"
                    // redo re-runs the original request, not a [Previous attempt]-
                    // augmented redo_input. Only the first attempt of a turn sets it.
                    if app_state.redo_count == 0 {
                        app_state.last_user_request = Some(ui_state.last_user_input.clone());
                    }

                    let mode = app_state.mode;
                    // Eval owns the final answer when a distinct eval model runs;
                    // otherwise (single-model / Plan) exec content stands as the answer.
                    // Fires when there is anything to reflect on — assistant text OR
                    // tool results (a tool-only step may have empty prose but a real
                    // answer in the tool log).
                    let eval_will_run = mode != AppMode::Plan
                        && (!content.is_empty() || !tool_log.is_empty())
                        && !app_state.config.eval_model.is_empty();

                    // Execute bash blocks (Auto) / show hint (Edit). Exec content is
                    // the work performed — applied here regardless of eval.
                    if !content.is_empty() {
                        if mode == AppMode::Auto {
                            execute_bash_blocks(&app_state, &mut ui_state, &content);
                        } else if mode == AppMode::Edit {
                            let bash_blocks = parse_bash_blocks(&content);
                            if !bash_blocks.is_empty() {
                                let cmd_count: usize = bash_blocks
                                    .iter()
                                    .map(|b| b.lines().filter(|l| !l.trim().is_empty()).count())
                                    .sum();
                                ui_state.add_output(OutputLine::System(format!(
                                    "Detected {} command(s). Use /run <cmd> to execute.",
                                    cmd_count
                                )));
                            }
                        }
                    }
                    // Handle file changes per mode (exec content is the file source).
                    if !content.is_empty() {
                        let changes = agent::parse_file_changes(&content);
                        if !changes.is_empty() {
                            for change in &changes {
                                app_state.working_set.touch(&change.path);
                            }
                            tracing::info!("detected {} file change(s) in response", changes.len());
                            for change in &changes {
                                tracing::info!(
                                    "  file change: {} {} ({} bytes content)",
                                    change.action,
                                    change.path.display(),
                                    change.content.len()
                                );
                            }
                            match mode {
                                AppMode::Auto => {
                                    auto_apply_changes(
                                        &mut app_state,
                                        &mut ui_state,
                                        &changes,
                                        &result_tx,
                                    );
                                    // Post-turn snapshot (non-fatal)
                                    if let Err(e) =
                                        app_state.snapshot_manager.post_turn("auto changes")
                                    {
                                        tracing::debug!("post-turn snapshot skipped: {}", e);
                                    }
                                    // End-of-turn recap for substantial auto changes
                                    if changes.len() > 2 && app_state.config.enable_recap {
                                        let history = app_state.conversation_history.clone();
                                        let config = app_state.config.clone();
                                        let tx = result_tx.clone();
                                        std::thread::spawn(move || {
                                            let rt = tokio::runtime::Runtime::new().unwrap();
                                            let result = rt.block_on(async {
                                                let client = ollama::OllamaClient::new(&config)?;
                                                recap::generate_recap(&client, &history, &config)
                                                    .await
                                            });
                                            if let Ok(summary) = result {
                                                let _ =
                                                    tx.send(agent::retry::PipelineResult::Retry(
                                                        agent::retry::RetryResult::Success {
                                                            content: format!(
                                                                "Turn recap: {}",
                                                                summary
                                                            ),
                                                            attempts: 0,
                                                        },
                                                    ));
                                            }
                                        });
                                    }
                                }
                                AppMode::Edit => {
                                    enter_file_confirmation(
                                        &mut app_state,
                                        &mut ui_state,
                                        &changes,
                                    );
                                }
                                AppMode::Plan => {
                                    ui_state.add_output(OutputLine::System(format!(
                                        "Detected {} file change(s). Switch to Edit/Auto to apply.",
                                        changes.len()
                                    )));
                                }
                            }
                        }
                    }

                    if eval_will_run {
                        // Eval reflection owns the final answer. Keep processing so
                        // queued input is not drained mid-eval; EvalReady finalizes.
                        ui_state.add_output(OutputLine::Phase("Eval".into()));
                        ui_state.start_thinking_phase("evaluating");
                        spawn_eval_reflection(
                            &app_state,
                            &ui_state.last_user_input,
                            app_state.last_plan.as_deref().unwrap_or(""),
                            &content,
                            &tool_log,
                            app_state.redo_count,
                            result_tx.clone(),
                        );
                    } else {
                        // Short-circuit (single-model or Plan): exec content is the
                        // answer. Commit it and finalize the turn here.
                        commit_assistant_answer(&mut app_state, &content, &result_tx);
                        app_state.is_processing = false;
                        ui_state.add_output(OutputLine::Separator);
                    }
                }
                agent::retry::PipelineResult::StreamMeta {
                    total_prompt_tokens,
                    model,
                    ..
                } => {
                    app_state.total_prompt_tokens = total_prompt_tokens;
                    let context_window =
                        ollama::model::estimate_context_window(&model).max(1);
                    let usage_pct =
                        total_prompt_tokens as f64 / context_window as f64 * 100.0;
                    if usage_pct >= 100.0 {
                        ui_state.add_output(OutputLine::Error(format!(
                            "Context OVERFLOW! {:.0}% of window used ({}/{} tokens). Use /clear to reset.",
                            usage_pct,
                            total_prompt_tokens,
                            context_window
                        )));
                    } else if usage_pct >= 80.0 {
                        ui_state.add_output(OutputLine::System(format!(
                            "Context {:.0}% full ({}/{} tokens). Consider /clear to start fresh.",
                            usage_pct,
                            total_prompt_tokens,
                            context_window
                        )));
                    }
                }
                agent::retry::PipelineResult::PlanReady { plan } => {
                    tracing::info!("plan ready: {} bytes", plan.len());
                    tracing::debug!("plan content:\n{}", plan);
                    ui_state.stop_thinking();
                    if plan.starts_with("(plan unavailable") {
                        // Plan step failed — extract actual error and proceed without plan
                        let error_detail = plan
                            .strip_prefix("(plan unavailable: ")
                            .and_then(|s| s.strip_suffix(')'))
                            .unwrap_or("unknown error");
                        ui_state.add_output(OutputLine::System(
                            format!("Plan skipped ({}). Executing directly...", error_detail),
                        ));
                        ui_state.start_thinking_phase("executing");
                        app_state.last_plan = Some(String::new());
                        spawn_execution_with_plan(
                            &app_state,
                            &ui_state.last_user_input,
                            "",
                            result_tx.clone(),
                        );
                    } else {
                        ui_state.add_output(OutputLine::Plan(plan.clone()));
                        if app_state.mode == AppMode::Auto || app_state.mode == AppMode::Plan {
                            // Auto/Plan mode: auto-execute
                            ui_state.start_thinking_phase("executing");
                            app_state.last_plan = Some(plan.clone());
                            spawn_execution_with_plan(
                                &app_state,
                                &ui_state.last_user_input,
                                &plan,
                                result_tx.clone(),
                            );
                        } else {
                            // Edit mode: wait for approval
                            app_state.pending_plan = Some(plan);
                            app_state.is_processing = false;
                            ui_state.add_output(OutputLine::System(
                                "Execute? y/n/o (y=yes, n=no, o=other):".into(),
                            ));
                        }
                    }
                }
                agent::retry::PipelineResult::StepStart {
                    step,
                    total,
                    description,
                } => {
                    ui_state.stop_thinking();
                    tracing::info!("executing step {}/{}: {}", step, total, description);
                    if step == 1 {
                        ui_state.add_output(OutputLine::Phase("Exec".into()));
                    }
                    ui_state.add_output(OutputLine::System(format!(
                        "Step {}/{}: {}",
                        step, total, description
                    )));
                    ui_state.start_thinking_phase("executing");
                }
                agent::retry::PipelineResult::SummaryReady {
                    summary,
                    summarized_count,
                } => {
                    tracing::info!(
                        "conversation summarized: {} messages compacted, {} byte summary",
                        summarized_count,
                        summary.len()
                    );
                    app_state.conversation_summary = Some(summary);
                    ui_state.add_output(OutputLine::System(format!(
                        "Context compacted ({} messages summarized)",
                        summarized_count
                    )));
                }
                agent::retry::PipelineResult::ToolStart { tool_name, call_id } => {
                    tracing::info!("tool started: {} ({})", tool_name, call_id);
                    ui_state.add_output(OutputLine::System(format!("  Running: {}...", tool_name)));
                }
                agent::retry::PipelineResult::ToolResultReady { result } => {
                    if result.success {
                        tracing::info!(
                            "tool completed: {} ({} bytes)",
                            result.tool_name,
                            result.output.len()
                        );
                        let preview: String = result.output.chars().take(200).collect();
                        ui_state.add_output(OutputLine::System(format!(
                            "  {} done: {}{}",
                            result.tool_name,
                            preview,
                            if result.output.len() > 200 { "..." } else { "" }
                        )));
                    } else {
                        tracing::warn!("tool failed: {} — {}", result.tool_name, result.output);
                        ui_state.add_output(OutputLine::Error(format!(
                            "  {} failed: {}",
                            result.tool_name, result.output
                        )));
                    }
                }
                agent::retry::PipelineResult::DiagnosticReady { result: diag } => {
                    if diag.has_errors() {
                        tracing::warn!(
                            "post-write diagnostics: {} errors in {} files",
                            diag.errors.len(),
                            diag.files_checked
                        );
                        for err in &diag.errors {
                            let loc = match err.line {
                                Some(l) => format!("{}:{}", err.file, l),
                                None => err.file.clone(),
                            };
                            ui_state.add_output(OutputLine::Error(format!(
                                "  diagnostic: {} — {}",
                                loc, err.message
                            )));
                        }
                    } else if diag.files_checked > 0 {
                        tracing::info!("diagnostics passed for {} files", diag.files_checked);
                    }
                }
                agent::retry::PipelineResult::EvalReady { verdict, model } => {
                    ui_state.stop_thinking();
                    tracing::info!(
                        "eval reflection ({}): satisfied={} summary={} bytes proposal={}",
                        model,
                        verdict.satisfied,
                        verdict.summary.len(),
                        verdict.proposal.is_some()
                    );
                    // The eval summary is the canonical answer. Fall back to the
                    // stashed exec content if the eval produced none.
                    let summary = if verdict.summary.trim().is_empty() {
                        app_state.last_exec_output.clone().unwrap_or_default()
                    } else {
                        agent::tools_parser::sanitize_output(&verdict.summary)
                    };
                    if !summary.trim().is_empty() {
                        ui_state.add_output(OutputLine::Assistant(summary.clone()));
                    }
                    commit_assistant_answer(&mut app_state, &summary, &result_tx);

                    // Decide: propose a redo, or finalize the turn.
                    let proposal = if !verdict.satisfied
                        && app_state.redo_count < MAX_REDOS_PER_TURN
                    {
                        verdict.proposal.clone()
                    } else {
                        None
                    };
                    match proposal {
                        Some(p) if app_state.awaiting_confirmation => {
                            // Edit file review still pending — hold the proposal and
                            // surface it once the last file is reviewed. The turn's
                            // LLM work is done, so allow the interactive review.
                            app_state.pending_redo_proposal = Some(p);
                            app_state.is_processing = false;
                            ui_state.add_output(OutputLine::System(
                                "Eval: result may be incomplete — a redo will be proposed \
                                 after file review."
                                    .into(),
                            ));
                        }
                        Some(p) => {
                            app_state.pending_redo_decision = Some(p);
                            app_state.is_processing = false;
                            ui_state.add_output(OutputLine::System(
                                "Eval: result may be incomplete. Redo? y/n/o \
                                 (y=accept proposal, n=keep result, o=your own instruction)"
                                    .into(),
                            ));
                        }
                        None => {
                            // Satisfied (or redo cap reached): finalize the turn.
                            ui_state.add_output(OutputLine::Separator);
                            app_state.is_processing = false;
                        }
                    }
                }
                agent::retry::PipelineResult::Status { message } => {
                    ui_state.add_output(OutputLine::System(message));
                }
            }

            // Drain next queued message only when the turn is truly complete —
            // not while eval is pending or a redo/file/plan approval awaits.
            if turn_is_complete(&app_state) && !app_state.pending_queue.is_empty() {
                let next = app_state.pending_queue.remove(0);
                tracing::info!(
                    "draining queued message: {:?} ({} remaining in queue)",
                    next,
                    app_state.pending_queue.len()
                );
                ui_state.add_output(OutputLine::System(
                    "Processing queued message...".to_string(),
                ));
                ui_state.add_output(OutputLine::User(next.clone()));
                ui_state.start_thinking_phase("planning");
                spawn_request_for_mode(&mut app_state, &ollama_client, &next, result_tx.clone());
                app_state.is_processing = true;
            }
        }

        // If Edit file review has finished and the eval stashed a redo proposal,
        // surface it now (runs every tick, so it needs no extra keypress).
        if !app_state.awaiting_confirmation
            && !app_state.is_processing
            && app_state.pending_redo_decision.is_none()
        {
            if let Some(p) = app_state.pending_redo_proposal.take() {
                app_state.pending_redo_decision = Some(p);
                ui_state.add_output(OutputLine::System(
                    "Eval: result may be incomplete. Redo? y/n/o \
                     (y=accept proposal, n=keep result, o=your own instruction)"
                        .into(),
                ));
            }
        }

        if event::poll(Duration::from_millis(100))? {
            let ev = event::read()?;
            match ev {
                Event::Paste(text) => {
                    ui_state.set_paste(text);
                }
                Event::Key(key) => {
                    // Handle edit confirmation keys (y/n/a) when awaiting
                    if app_state.awaiting_confirmation && key.modifiers == KeyModifiers::NONE {
                        match key.code {
                            KeyCode::Char('y') => {
                                // Destructive ops need double-key (YY)
                                if app_state.awaiting_destructive_confirm {
                                    app_state.awaiting_destructive_confirm = false;
                                    // Second Y confirmed — proceed
                                } else {
                                    // Check if current action is destructive
                                    if let Some(action) = app_state.pending_confirmations.last() {
                                        let risk = pending_action_risk(action);
                                        if risk == approval::RiskLevel::Destructive {
                                            ui_state.add_output(OutputLine::System(
                                                "Destructive! Press Y again to confirm.".into(),
                                            ));
                                            app_state.awaiting_destructive_confirm = true;
                                            continue;
                                        }
                                    }
                                }
                                // Apply the next pending file
                                if let Some(action) = app_state.pending_confirmations.pop() {
                                    tracing::info!(
                                        "user confirmed: applying file ({} remaining)",
                                        app_state.pending_confirmations.len()
                                    );
                                    let sandbox =
                                        sandbox::Sandbox::new(app_state.workspace.clone());
                                    apply_pending_action(
                                        &mut ui_state,
                                        &app_state,
                                        action,
                                        &sandbox,
                                    );
                                }
                                if app_state.pending_confirmations.is_empty() {
                                    app_state.awaiting_confirmation = false;
                                    ui_state.add_output(OutputLine::System(
                                        "All files reviewed.".into(),
                                    ));
                                } else {
                                    ui_state.add_output(OutputLine::System(format!(
                                        "Apply next? ({} remaining) y/n/a/o (y=yes, n=no, a=apply all, o=other):",
                                        app_state.pending_confirmations.len()
                                    )));
                                }
                                continue;
                            }
                            KeyCode::Char('n') => {
                                // Skip this file
                                if let Some(action) = app_state.pending_confirmations.pop() {
                                    tracing::info!(
                                        "user skipped file ({} remaining)",
                                        app_state.pending_confirmations.len()
                                    );
                                    let path = match &action {
                                        app::PendingAction::WriteFile { path, .. } => {
                                            path.display().to_string()
                                        }
                                        app::PendingAction::DeleteFile { path } => {
                                            path.display().to_string()
                                        }
                                        app::PendingAction::ExecuteCommand { cmd, .. } => {
                                            cmd.clone()
                                        }
                                    };
                                    ui_state.add_output(OutputLine::System(format!(
                                        "Skipped {}",
                                        path
                                    )));
                                }
                                if app_state.pending_confirmations.is_empty() {
                                    app_state.awaiting_confirmation = false;
                                    ui_state.add_output(OutputLine::System(
                                        "All files reviewed.".into(),
                                    ));
                                } else {
                                    ui_state.add_output(OutputLine::System(format!(
                                        "Apply next? ({} remaining) y/n/a/o (y=yes, n=no, a=apply all, o=other):",
                                        app_state.pending_confirmations.len()
                                    )));
                                }
                                continue;
                            }
                            KeyCode::Char('a') => {
                                // Apply all remaining
                                tracing::info!(
                                    "user chose apply-all for {} remaining file(s)",
                                    app_state.pending_confirmations.len()
                                );
                                let sandbox = sandbox::Sandbox::new(app_state.workspace.clone());
                                let remaining =
                                    std::mem::take(&mut app_state.pending_confirmations);
                                let total = remaining.len();
                                let mut applied = 0;
                                for action in remaining {
                                    apply_pending_action(
                                        &mut ui_state,
                                        &app_state,
                                        action,
                                        &sandbox,
                                    );
                                    applied += 1;
                                }
                                app_state.awaiting_confirmation = false;
                                ui_state.add_output(OutputLine::System(format!(
                                    "Applied {}/{} remaining file(s)",
                                    applied, total
                                )));
                                continue;
                            }
                            KeyCode::Char('o') => {
                                // Other: user provides custom feedback
                                tracing::info!(
                                    "user chose Other for file review ({} pending cancelled)",
                                    app_state.pending_confirmations.len()
                                );
                                app_state.clear_pending();
                                app_state.awaiting_confirmation = false;
                                app_state.awaiting_other_input = true;
                                ui_state.add_output(OutputLine::System(
                                    "Other: (type your response and press Enter)".into(),
                                ));
                                continue;
                            }
                            _ => {} // Fall through to normal key handling
                        }
                    }

                    // Plan approval: 'y' to execute, 'n' to cancel
                    if app_state.pending_plan.is_some()
                        && key.modifiers == KeyModifiers::NONE
                    {
                        match key.code {
                            KeyCode::Char('y') => {
                                if let Some(plan) = app_state.pending_plan.take() {
                                    ui_state.add_output(OutputLine::System("Executing plan...".into()));
                                    ui_state.start_thinking_phase("executing");
                                    app_state.is_processing = true;
                                    app_state.last_plan = Some(plan.clone());
                                    spawn_execution_with_plan(
                                        &app_state,
                                        &ui_state.last_user_input,
                                        &plan,
                                        result_tx.clone(),
                                    );
                                }
                                continue;
                            }
                            KeyCode::Char('n') => {
                                if app_state.pending_plan.take().is_some() {
                                    ui_state.add_output(OutputLine::System("Plan cancelled.".into()));
                                }
                                continue;
                            }
                            _ => {} // fall through to 'o' handler and normal input
                        }
                    }

                    // Plan approval: 'o' for Other feedback
                    if app_state.pending_plan.is_some()
                        && key.modifiers == KeyModifiers::NONE
                        && key.code == KeyCode::Char('o')
                    {
                        app_state.pending_plan = None;
                        app_state.awaiting_other_input = true;
                        ui_state.add_output(OutputLine::System(
                            "Other: (type your response and press Enter)".into(),
                        ));
                        continue;
                    }

                    // Eval-redo approval: 'y' to run the proposed redo, 'n' to keep
                    // the current result, 'o' for the user's own instruction.
                    if app_state.pending_redo_decision.is_some()
                        && key.modifiers == KeyModifiers::NONE
                    {
                        match key.code {
                            KeyCode::Char('y') => {
                                if let Some(proposal) = app_state.pending_redo_decision.take() {
                                    run_eval_redo(
                                        &mut app_state,
                                        &ollama_client,
                                        &mut ui_state,
                                        proposal,
                                        result_tx.clone(),
                                    );
                                }
                                continue;
                            }
                            KeyCode::Char('n') => {
                                if app_state.pending_redo_decision.take().is_some() {
                                    ui_state.add_output(OutputLine::System(
                                        "Keeping current result.".into(),
                                    ));
                                    ui_state.add_output(OutputLine::Separator);
                                }
                                continue;
                            }
                            _ => {} // fall through to 'o' handler and normal input
                        }
                    }

                    // Eval-redo approval: 'o' for own instruction
                    if app_state.pending_redo_decision.is_some()
                        && key.modifiers == KeyModifiers::NONE
                        && key.code == KeyCode::Char('o')
                    {
                        app_state.pending_redo_decision = None;
                        app_state.awaiting_other_input = true;
                        ui_state.add_output(OutputLine::System(
                            "Other: (type your response and press Enter)".into(),
                        ));
                        continue;
                    }

                    match (key.modifiers, key.code) {
                        // Shift+Tab: switch mode (crossterm sends BackTab for Shift+Tab)
                        (_, KeyCode::BackTab) => {
                            let old_mode = app_state.mode;
                            let new_mode = app_state.switch_mode();
                            app_state.prompt_builder.set_mode(new_mode);
                            tracing::info!("mode switch: {} -> {}", old_mode, new_mode);
                            ui_state.add_output(OutputLine::System(format!(
                                "Switched to {} mode",
                                new_mode
                            )));
                        }
                        // Ctrl+C: quit
                        (KeyModifiers::CONTROL, KeyCode::Char('c')) => {
                            tracing::info!("user requested quit (Ctrl+C)");
                            if app_state.mode == AppMode::Auto {
                                ui_state.add_output(OutputLine::System(
                                    "Press Ctrl+C again to confirm quit from AUTO mode".into(),
                                ));
                                // Simple double-press: check next event
                                if event::poll(Duration::from_secs(2))? {
                                    if let Event::Key(k2) = event::read()? {
                                        if k2.code == KeyCode::Char('c')
                                            && k2.modifiers.contains(KeyModifiers::CONTROL)
                                        {
                                            break;
                                        }
                                    }
                                }
                            } else {
                                break;
                            }
                        }
                        // Ctrl+Tab: toggle model thinking
                        (KeyModifiers::CONTROL, KeyCode::Tab) => {
                            app_state.think_enabled = !app_state.think_enabled;
                            let state = if app_state.think_enabled {
                                "THINK"
                            } else {
                                "DIRECT"
                            };
                            tracing::info!("think mode: {}", state);
                            ui_state
                                .add_output(OutputLine::System(format!("Model mode: {}", state)));
                        }
                        // Shift+Enter: insert newline
                        (KeyModifiers::SHIFT, KeyCode::Enter) => {
                            ui_state.push_char('\n');
                        }
                        // Enter: submit input or approve pending plan
                        (KeyModifiers::NONE, KeyCode::Enter) => {
                            // Other input: submit user feedback
                            if app_state.awaiting_other_input {
                                let input = ui_state.take_input();
                                if !input.is_empty() {
                                    app_state.awaiting_other_input = false;
                                    tracing::info!("user Other input: {}", input.trim());
                                    ui_state.add_output(OutputLine::User(input.clone()));
                                    app_state.conversation_history.push(
                                        app::ConversationMessage {
                                            role: "user".into(),
                                            content: input.clone(),
                                            tokens: 0,
                                        },
                                    );
                                    ui_state.start_thinking_phase("planning");
                                    spawn_request_for_mode(
                                        &mut app_state,
                                        &ollama_client,
                                        &input,
                                        result_tx.clone(),
                                    );
                                    app_state.is_processing = true;
                                } else {
                                    ui_state.add_output(OutputLine::System(
                                        "Cancelled.".into(),
                                    ));
                                    app_state.awaiting_other_input = false;
                                }
                                continue;
                            }

                            let input = ui_state.take_input();
                            if !input.is_empty() {
                                app_state.record_input(input.clone());
                                // A brand-new user request starts a fresh turn —
                                // reset the eval-redo counter (redos bypass this).
                                app_state.redo_count = 0;
                                tracing::info!("user input: {}", input.trim());
                                tracing::debug!(
                                    "conversation history: {} messages, queue: {}",
                                    app_state.conversation_history.len(),
                                    app_state.pending_queue.len()
                                );
                                ui_state.last_user_input = input.clone();

                                if input.trim() == "/quit" || input.trim() == "/exit" {
                                    tracing::info!(
                                        "session ending via /{}",
                                        input.trim().trim_start_matches('/')
                                    );
                                    break;
                                }

                                // Handle slash commands (instant, no LLM call)
                                let trimmed = input.trim();
                                if trimmed == "/clear" {
                                    app_state.total_prompt_tokens = 0;
                                    app_state.conversation_history.clear();
                                    app_state.conversation_summary = None;
                                    ui_state.clear_output();
                                    ui_state.add_output(OutputLine::System(
                                        "Context cleared. Starting fresh session.".into(),
                                    ));
                                    ui_state.add_output(OutputLine::System(
                                        "Shift+Tab: mode | Enter: send | Shift+Enter: newline | Ctrl+Tab: think | Ctrl+C: quit | /skills: list skills".into(),
                                    ));
                                } else if trimmed == "/skills" {
                                    let skills = app_state.skills.list();
                                    if skills.is_empty() {
                                        ui_state.add_output(OutputLine::System(
                                            "No skills loaded.".into(),
                                        ));
                                    } else {
                                        let mut lines = vec!["Available skills:".to_string()];
                                        for s in skills {
                                            lines
                                                .push(format!("  /{} — {}", s.name, s.description));
                                        }
                                        ui_state.add_output(OutputLine::System(lines.join("\n")));
                                    }
                                } else if trimmed == "/setup" {
                                    tracing::info!("running setup wizard");
                                    match wizard::run(
                                        terminal,
                                        app_state.config.clone(),
                                        &app_state.workspace,
                                    ) {
                                        Ok(new_config) => {
                                            app_state.config = new_config;
                                            ui_state.add_output(OutputLine::System(
                                                "Setup complete. Configuration updated.".into(),
                                            ));
                                        }
                                        Err(e) => {
                                            ui_state.add_output(OutputLine::Error(format!(
                                                "Setup wizard failed: {}",
                                                e
                                            )));
                                        }
                                    }
                                    let skills = app_state.skills.list();
                                    if skills.is_empty() {
                                        ui_state.add_output(OutputLine::System(
                                            "No skills loaded.".into(),
                                        ));
                                    } else {
                                        let mut lines = vec!["Available skills:".to_string()];
                                        for s in skills {
                                            lines
                                                .push(format!("  /{} — {}", s.name, s.description));
                                        }
                                        ui_state.add_output(OutputLine::System(lines.join("\n")));
                                    }
                                } else if trimmed == "/recap" {
                                    // Generate a recap of the current session
                                    if !app_state.config.enable_recap {
                                        ui_state.add_output(OutputLine::System(
                                            "Recap is disabled in config.".into(),
                                        ));
                                    } else {
                                        let history = app_state.conversation_history.clone();
                                        let config = app_state.config.clone();
                                        let tx = result_tx.clone();
                                        ui_state.add_output(OutputLine::System(
                                            "Generating recap...".into(),
                                        ));
                                        std::thread::spawn(move || {
                                            let rt = tokio::runtime::Runtime::new().unwrap();
                                            let result = rt.block_on(async {
                                                let client = ollama::OllamaClient::new(&config)?;
                                                recap::generate_recap(&client, &history, &config)
                                                    .await
                                            });
                                            match result {
                                                Ok(summary) => {
                                                    let _ = tx.send(
                                                        agent::retry::PipelineResult::Retry(
                                                            agent::retry::RetryResult::Success {
                                                                content: format!(
                                                                    "Recap: {}",
                                                                    summary
                                                                ),
                                                                attempts: 0,
                                                            },
                                                        ),
                                                    );
                                                }
                                                Err(e) => {
                                                    let _ = tx.send(
                                                        agent::retry::PipelineResult::Retry(
                                                            agent::retry::RetryResult::Failed {
                                                                last_error: format!(
                                                                    "Recap failed: {}",
                                                                    e
                                                                ),
                                                                attempts: 0,
                                                            },
                                                        ),
                                                    );
                                                }
                                            }
                                        });
                                    } // end enable_recap guard
                                } else if trimmed == "/snapshots" || trimmed == "/snaps" {
                                    match app_state.snapshot_manager.list(10) {
                                        Ok(entries) => {
                                            if entries.is_empty() {
                                                ui_state.add_output(OutputLine::System(
                                                    "No snapshots yet.".into(),
                                                ));
                                            } else {
                                                let mut lines =
                                                    vec!["Recent snapshots:".to_string()];
                                                for (i, e) in entries.iter().enumerate() {
                                                    lines.push(format!(
                                                        "  {} {} {}",
                                                        &e.hash[..8],
                                                        e.date,
                                                        e.message
                                                    ));
                                                    if i >= 9 {
                                                        break;
                                                    }
                                                }
                                                lines.push(
                                                    "Use /undo to restore last, /restore <hash> for specific"
                                                        .into(),
                                                );
                                                ui_state.add_output(OutputLine::System(
                                                    lines.join("\n"),
                                                ));
                                            }
                                        }
                                        Err(e) => {
                                            ui_state.add_output(OutputLine::Error(format!(
                                                "Snapshot list failed: {}",
                                                e
                                            )));
                                        }
                                    }
                                } else if trimmed == "/undo" {
                                    match app_state.snapshot_manager.list(2) {
                                        Ok(entries) => {
                                            if entries.len() < 2 {
                                                ui_state.add_output(OutputLine::Error(
                                                    "No snapshot to undo to.".into(),
                                                ));
                                            } else {
                                                let target = &entries[1];
                                                match app_state
                                                    .snapshot_manager
                                                    .restore(&target.hash)
                                                {
                                                    Ok(()) => {
                                                        ui_state.add_output(OutputLine::System(
                                                            format!(
                                                                "Restored to {} ({})",
                                                                &target.hash[..8],
                                                                target.message
                                                            ),
                                                        ));
                                                    }
                                                    Err(e) => {
                                                        ui_state.add_output(OutputLine::Error(
                                                            format!("Restore failed: {}", e),
                                                        ));
                                                    }
                                                }
                                            }
                                        }
                                        Err(e) => {
                                            ui_state.add_output(OutputLine::Error(format!(
                                                "Snapshot access failed: {}",
                                                e
                                            )));
                                        }
                                    }
                                } else if trimmed.starts_with("/restore ") {
                                    let hash = trimmed.trim_start_matches("/restore ").trim();
                                    if hash.is_empty() {
                                        ui_state.add_output(OutputLine::Error(
                                            "Usage: /restore <commit-hash>".into(),
                                        ));
                                    } else {
                                        match app_state.snapshot_manager.restore(hash) {
                                            Ok(()) => {
                                                ui_state.add_output(OutputLine::System(format!(
                                                    "Restored to {}",
                                                    &hash[..hash.len().min(8)]
                                                )));
                                            }
                                            Err(e) => {
                                                ui_state.add_output(OutputLine::Error(format!(
                                                    "Restore failed: {}",
                                                    e
                                                )));
                                            }
                                        }
                                    }
                                } else if trimmed == "/apply" {
                                    // Apply file changes from the last assistant response
                                    tracing::info!(
                                        "applying file changes, mode={}",
                                        app_state.mode
                                    );
                                    tracing::debug!(
                                        "conversation history length: {} messages",
                                        app_state.conversation_history.len()
                                    );
                                    let last_content = ui_state.output_lines.iter().rev().find_map(
                                        |ol| match ol {
                                            OutputLine::Assistant(t) => Some(t.clone()),
                                            _ => None,
                                        },
                                    );
                                    if let Some(ref content) = last_content {
                                        let changes =
                                            agent::parse_file_changes(content);
                                        if changes.is_empty() {
                                            ui_state.add_output(OutputLine::Error(
                                                "No file changes found in the last response."
                                                    .into(),
                                            ));
                                        } else if app_state.mode == AppMode::Edit {
                                            // Edit mode: queue confirmations for y/n review
                                            let sandbox =
                                                sandbox::Sandbox::new(app_state.workspace.clone());
                                            let file_ops = project::file_ops::FileOps::new(
                                                &sandbox,
                                                app_state.mode,
                                            );
                                            app_state.clear_pending();
                                            let mut queued = 0;
                                            for change in &changes {
                                                let full_path =
                                                    app_state.workspace.join(&change.path);
                                                let fc = match if change.action == "delete" {
                                                    file_ops.prepare_delete(&full_path)
                                                } else {
                                                    file_ops
                                                        .prepare_write(&full_path, &change.content)
                                                } {
                                                    Ok(fc) => fc,
                                                    Err(e) => {
                                                        ui_state.add_output(OutputLine::Error(
                                                            format!(
                                                                "Blocked {}: {}",
                                                                change.path.display(),
                                                                e
                                                            ),
                                                        ));
                                                        continue;
                                                    }
                                                };

                                                // Show diff preview
                                                if !fc.diff_preview.is_empty() {
                                                    ui_state.add_output(OutputLine::System(
                                                        format!("--- {}", change.path.display()),
                                                    ));
                                                    for line in fc.diff_preview.lines() {
                                                        if line.starts_with('-')
                                                            && !line.starts_with("---")
                                                        {
                                                            ui_state.add_output(OutputLine::Diff {
                                                                added: vec![],
                                                                removed: vec![line.to_string()],
                                                            });
                                                        } else if line.starts_with('+')
                                                            && !line.starts_with("+++")
                                                        {
                                                            ui_state.add_output(OutputLine::Diff {
                                                                added: vec![line.to_string()],
                                                                removed: vec![],
                                                            });
                                                        }
                                                    }
                                                }

                                                let action = if change.action == "delete" {
                                                    app::PendingAction::DeleteFile {
                                                        path: full_path,
                                                    }
                                                } else {
                                                    app::PendingAction::WriteFile {
                                                        path: full_path,
                                                        content: change.content.clone(),
                                                        diff_preview: fc.diff_preview,
                                                    }
                                                };
                                                app_state.push_pending(action);
                                                queued += 1;
                                            }
                                            if queued > 0 {
                                                app_state.awaiting_confirmation = true;
                                                ui_state.add_output(OutputLine::System(format!(
                                                "Review {} file(s). y/n/a/o (y=yes, n=no, a=apply all, o=other):",
                                                queued
                                            )));
                                            }
                                        } else {
                                            // Auto mode: apply all immediately (Plan mode blocked by FileOps)
                                            let sandbox =
                                                sandbox::Sandbox::new(app_state.workspace.clone());
                                            let file_ops = project::file_ops::FileOps::new(
                                                &sandbox,
                                                app_state.mode,
                                            );
                                            let mut applied = 0;
                                            for change in &changes {
                                                let full_path =
                                                    app_state.workspace.join(&change.path);
                                                let fc = match if change.action == "delete" {
                                                    file_ops.prepare_delete(&full_path)
                                                } else {
                                                    file_ops
                                                        .prepare_write(&full_path, &change.content)
                                                } {
                                                    Ok(fc) => fc,
                                                    Err(e) => {
                                                        ui_state.add_output(OutputLine::Error(
                                                            format!(
                                                                "Blocked {}: {}",
                                                                change.path.display(),
                                                                e
                                                            ),
                                                        ));
                                                        continue;
                                                    }
                                                };
                                                match file_ops.apply_change(&fc) {
                                                    Ok(()) => {
                                                        ui_state.add_output(OutputLine::System(
                                                            format!(
                                                                "Wrote {}",
                                                                change.path.display()
                                                            ),
                                                        ));
                                                        applied += 1;
                                                        run_syntax_check(
                                                            &mut ui_state,
                                                            &app_state.workspace.join(&change.path),
                                                            &sandbox,
                                                        );
                                                    }
                                                    Err(e) => {
                                                        ui_state.add_output(OutputLine::Error(
                                                            format!(
                                                                "Failed to write {}: {}",
                                                                change.path.display(),
                                                                e
                                                            ),
                                                        ));
                                                    }
                                                }
                                            }
                                            ui_state.add_output(OutputLine::System(format!(
                                                "Applied {}/{} file(s)",
                                                applied,
                                                changes.len()
                                            )));
                                        }
                                    } else {
                                        ui_state.add_output(OutputLine::Error(
                                            "No assistant response to apply.".into(),
                                        ));
                                    }
                                } else if let Some(uv_args) = trimmed.strip_prefix("/uv ") {
                                    // /uv commands: init, venv, add <pkg>, run <script>
                                    handle_uv_command(
                                        &mut app_state,
                                        &mut ui_state,
                                        uv_args.trim(),
                                    );
                                } else if trimmed == "/uv" {
                                    ui_state.add_output(OutputLine::System(
                                    "Usage: /uv init | /uv venv | /uv add <package> | /uv run <script>".into(),
                                ));
                                } else if let Some(run_cmd) = trimmed.strip_prefix("/run ") {
                                    handle_run_command(
                                        &mut app_state,
                                        &mut ui_state,
                                        run_cmd.trim(),
                                    );
                                } else if let Some(cmd) = trimmed.strip_prefix('/') {
                                    let (skill_name, args) = match cmd.split_once(' ') {
                                        Some((name, rest)) => (name, rest.trim()),
                                        None => (cmd, ""),
                                    };

                                    if let Some(skill) = app_state.skills.get(skill_name).cloned() {
                                        tracing::info!("skill: /{} {:?}", skill_name, args);
                                        let full_input = if args.is_empty() {
                                            String::new()
                                        } else {
                                            args.to_string()
                                        };
                                        if app_state.is_processing {
                                            // Queue skill invocation
                                            let label = format!("/{} {}", skill_name, full_input)
                                                .trim_end()
                                                .to_string();
                                            app_state.pending_queue.push(label.clone());
                                            ui_state.add_output(OutputLine::Pending(label));
                                        } else {
                                            ui_state.add_output(OutputLine::User(input.clone()));
                                            ui_state.start_thinking();
                                            spawn_skill_request(
                                                &app_state,
                                                &ollama_client,
                                                &skill,
                                                &full_input,
                                                result_tx.clone(),
                                            );
                                            app_state.is_processing = true;
                                        }
                                    } else {
                                        ui_state.add_output(OutputLine::Error(format!(
                                        "Unknown skill: /{}. Type /skills to see available skills.",
                                        skill_name
                                    )));
                                    }
                                } else if app_state.is_processing {
                                    // Queue the message for later processing
                                    app_state.pending_queue.push(input.clone());
                                    ui_state.add_output(OutputLine::Pending(input));
                                } else {
                                    // Display user message immediately and spawn background request
                                    ui_state.add_output(OutputLine::User(input.clone()));
                                    // Record in conversation history
                                    app_state.conversation_history.push(ConversationMessage {
                                        role: "user".into(),
                                        content: input.clone(),
                                        tokens: util::text::estimate_tokens(&input),
                                    });
                                    // Record in session
                                    app_state.current_session.add_message("user", &input);
                                    ui_state.start_thinking_phase("planning");
                                    spawn_request_for_mode(
                                        &mut app_state,
                                        &ollama_client,
                                        &input,
                                        result_tx.clone(),
                                    );
                                    app_state.is_processing = true;
                                }
                            }
                        }
                        // Backspace
                        (KeyModifiers::NONE, KeyCode::Backspace) => {
                            ui_state.backspace();
                        }
                        // Escape: cancel other input
                        (KeyModifiers::NONE, KeyCode::Esc) => {
                            if app_state.awaiting_other_input {
                                app_state.awaiting_other_input = false;
                                ui_state.input_text.clear();
                                ui_state.input_cursor = 0;
                                ui_state.add_output(OutputLine::System("Cancelled.".into()));
                            }
                        }
                        // Page Up/Down: no virtual scrolling (terminal native scrollback)
                        // Character input (allow NONE or SHIFT for uppercase)
                        (KeyModifiers::NONE | KeyModifiers::SHIFT, KeyCode::Char(c)) => {
                            app_state.history_index = 0;
                            ui_state.push_char(c);
                        }
                        // Up arrow: navigate input history (older)
                        (KeyModifiers::NONE, KeyCode::Up) => {
                            if !app_state.input_history.is_empty()
                                && app_state.history_index < app_state.input_history.len()
                            {
                                app_state.history_index += 1;
                                let idx = app_state.input_history.len() - app_state.history_index;
                                ui_state.input_text = app_state.input_history[idx].clone();
                                ui_state.input_cursor = ui_state.input_text.chars().count();
                            }
                        }
                        // Down arrow: navigate input history (newer)
                        (KeyModifiers::NONE, KeyCode::Down) => {
                            if app_state.history_index > 0 {
                                app_state.history_index -= 1;
                                if app_state.history_index == 0 {
                                    ui_state.input_text.clear();
                                    ui_state.input_cursor = 0;
                                } else {
                                    let idx =
                                        app_state.input_history.len() - app_state.history_index;
                                    ui_state.input_text = app_state.input_history[idx].clone();
                                    ui_state.input_cursor = ui_state.input_text.chars().count();
                                }
                            }
                        }
                        _ => {}
                    }
                }
                _ => {}
            }
        }
    }

    Ok(())
}

/// Flush pending inline output above the viewport using `terminal.insert_before()`.
fn flush_pending_output(
    terminal: &mut Terminal<CrosstermBackend<io::Stdout>>,
    ui_state: &mut ui::UiState,
) -> Result<()> {
    if ui_state.pending_inline.is_empty() {
        return Ok(());
    }
    let lines = std::mem::take(&mut ui_state.pending_inline);
    let theme = &ui_state.theme;
    let width = terminal.size()?.width;
    let line_count = ui::inline::estimate_line_count(&lines, width);

    terminal.insert_before(line_count, |buf| {
        ui::inline::render_output_lines(buf, &lines, &theme);
    })?;
    Ok(())
}

/// Plan-then-execute: runs a quick plan step on the exec model, sends PlanReady,
/// then the main loop waits for user approval before calling spawn_execution_with_plan.
fn spawn_plan_then_execute(
    app_state: &AppState,
    _client: &ollama::OllamaClient,
    input: &str,
    tx: mpsc::Sender<agent::retry::PipelineResult>,
) {
    let exec_model = app_state.config.exec_model.clone();
    let plan_model = app_state.config.effective_plan_model().to_string();
    let endpoint = app_state.config.ollama_endpoint.clone();
    let connect_timeout = app_state.config.connect_timeout;
    let context_window_limit = app_state.config.context_window_limit;
    let max_file_lines = app_state.config.max_file_lines;
    let input = input.to_string();
    let history_ctx = app_state
        .conversation_history
        .iter()
        .rev()
        .take(6)
        .map(|m| format!("{}: {}", m.role, m.content))
        .collect::<Vec<_>>()
        .join("\n");
    let plan_mode = app_state.mode == AppMode::Plan;
    let workspace = app_state.workspace.clone();

    // Build tool descriptions once on the main thread (cheap: just registers handlers).
    // The planner only sees prose names/descriptions — no native tool-calling. It emits
    // text steps that reference tools; the executor (spawn_execution_with_plan) does the
    // actual dispatch.
    let tools_description = tools::ToolRegistry::new(workspace.clone(), &app_state.config)
        .descriptions_text();

    // Compute the auto-injected skills block on the main thread (it borrows
    // app_state.skills, which can't travel into the 'static spawned closure).
    let planner_skills_block =
        matched_skills_block(&input, &app_state.skills, MAX_MATCHED_SKILL_TOKENS);

    tracing::info!(
        "spawn_plan_then_execute: plan_model={}, history_msgs={}, workspace={}, tools_chars={}",
        plan_model,
        app_state.conversation_history.len(),
        workspace.display(),
        tools_description.chars().count()
    );

    std::thread::spawn(move || {
        let rt = match tokio::runtime::Runtime::new() {
            Ok(rt) => rt,
            Err(e) => {
                let _ = tx.send(agent::retry::PipelineResult::Retry(
                    agent::retry::RetryResult::Failed {
                        last_error: format!("Runtime error: {}", e),
                        attempts: 0,
                    },
                ));
                return;
            }
        };

        let bg_config = config::Config {
            ollama_endpoint: endpoint,
            connect_timeout,
            exec_model: exec_model.clone(),
            context_window_limit,
            ..config::Config::default()
        };
        let bg_client = match ollama::OllamaClient::new(&bg_config) {
            Ok(c) => c,
            Err(e) => {
                let _ = tx.send(agent::retry::PipelineResult::Retry(
                    agent::retry::RetryResult::Failed {
                        last_error: format!("Client error: {}", e),
                        attempts: 0,
                    },
                ));
                return;
            }
        };

        // Quick plan step using the plan model (falls back to exec model).
        let project_listing = std::fs::read_dir(&workspace)
            .map(|entries| {
                entries
                    .filter_map(|e| e.ok())
                    .map(|e| e.file_name().to_string_lossy().to_string())
                    .collect::<Vec<_>>()
                    .join(", ")
            })
            .unwrap_or_default();
        let user_msg = format!(
            "Working directory: {}\nFiles in directory: {}\nCurrent date: {}\n\n{}\nNew request: {}",
            workspace.display(),
            project_listing,
            current_datetime(),
            if history_ctx.is_empty() {
                String::new()
            } else {
                format!("Recent context:\n{}\n\n", history_ctx)
            },
            input
        );
        let mut planner_system = apply_plan_prompt(
            agent::prompts::QUICK_PLAN_SYSTEM,
            max_file_lines,
            &tools_description,
        );
        // Auto-inject any skills whose trigger keywords match the user's input,
        // so the plan reflects relevant domain rules (e.g. count-files methodology).
        planner_system.push_str(&planner_skills_block);
        let messages = vec![
            ollama::chat::ChatMessage::system(planner_system),
            ollama::chat::ChatMessage::user(&user_msg),
        ];

        match rt.block_on(bg_client.chat(&plan_model, messages, false)) {
            Ok(resp) => {
                let plan = resp.content;
                let _ = tx.send(agent::retry::PipelineResult::PlanReady { plan: plan.clone() });
                // In Plan mode, auto-continue to execution (read-only analysis)
                if plan_mode {
                    // The main loop will handle this: Plan mode skips the approval gate
                }
            }
            Err(e) => {
                // Plan step failed — fall back to direct streaming without plan
                tracing::warn!("plan step failed for plan model '{}': {}", plan_model, e);
                let _ = tx.send(agent::retry::PipelineResult::PlanReady {
                    plan: format!("(plan unavailable: plan model '{}' — {})", plan_model, e),
                });
            }
        }
    });
}

/// Execute with a plan: step-by-step execution, one plan step per LLM call.
fn spawn_execution_with_plan(
    app_state: &AppState,
    input: &str,
    plan: &str,
    tx: mpsc::Sender<agent::retry::PipelineResult>,
) {
    let model = app_state.config.exec_model.clone();
    if model.is_empty() {
        let _ = tx.send(agent::retry::PipelineResult::Retry(
            agent::retry::RetryResult::Failed {
                last_error: "No core model configured.".into(),
                attempts: 0,
            },
        ));
        return;
    }

    let input = input.to_string();
    let plan = plan.to_string();
    let history = app_state.conversation_history.clone();
    let workspace = app_state.workspace.clone();
    let context_window_limit = app_state.config.context_window_limit;
    let now = current_datetime();

    // Tool registry for per-step tool dispatch. Built once outside the step loop and
    // shared across all steps in this execution. Native tool calls (`tools=[…]` on
    // `/api/chat`) are dispatched through this registry by `stream_step_native_tools`.
    let config = app_state.config.clone();
    let tool_registry = tools::ToolRegistry::new(workspace.clone(), &config);

    // Build system prompt via PromptBuilder (already updated before calling this function),
    // then auto-inject any skills whose trigger keywords match the user's input so the
    // executor and its final answer reflect relevant domain rules.
    let mut coding_system = app_state.prompt_builder.build();
    coding_system.push_str(&matched_skills_block(
        &input,
        &app_state.skills,
        MAX_MATCHED_SKILL_TOKENS,
    ));

    tracing::info!(
        "spawn_execution_with_plan: model={}, plan={} bytes, history_msgs={}, context_window={}",
        model,
        plan.len(),
        history.len(),
        context_window_limit,
    );

    std::thread::spawn(move || {
        let rt = match tokio::runtime::Runtime::new() {
            Ok(rt) => rt,
            Err(e) => {
                let _ = tx.send(agent::retry::PipelineResult::Retry(
                    agent::retry::RetryResult::Failed {
                        last_error: format!("Runtime error: {}", e),
                        attempts: 0,
                    },
                ));
                return;
            }
        };

        let client = match ollama::OllamaClient::new(&config) {
            Ok(c) => c,
            Err(e) => {
                let _ = tx.send(agent::retry::PipelineResult::Retry(
                    agent::retry::RetryResult::Failed {
                        last_error: format!("Client error: {}", e),
                        attempts: 0,
                    },
                ));
                return;
            }
        };

        // Conversation history as native chat messages for /api/chat.
        let native_history: Vec<serde_json::Value> = history
            .iter()
            .filter(|m| m.role != "system")
            .map(|m| serde_json::json!({ "role": m.role, "content": m.content }))
            .collect();

        // Parse plan into individual steps
        let steps: Vec<String> = plan
            .lines()
            .filter_map(|line| {
                let trimmed = line.trim();
                if trimmed.is_empty() {
                    return None;
                }
                let rest = trimmed.trim_start_matches(|c: char| c.is_ascii_digit());
                if rest.len() == trimmed.len() {
                    return None;
                }
                rest.strip_prefix('.')
                    .or_else(|| rest.strip_prefix(')'))
                    .map(|s| s.trim().to_string())
                    .filter(|s| !s.is_empty())
            })
            .collect();

        if steps.is_empty() {
            tracing::info!(
                "no parseable steps in plan, executing as single request (plan: {} bytes)",
                plan.len()
            );
            let output_budget = context_window_limit / 4;
            let system_prompt = format!(
                "{}\n\nWorking directory: {}\nCurrent date: {}\nOutput limit: keep response under {} tokens ({} lines max). If the task is too large, output only the first part and note what remains.",
                coding_system,
                workspace.display(),
                now,
                output_budget,
                output_budget / 4,
            );
            let user_message = format!("[Plan]\n{}\n\n{}", plan, input);
            let total_tokens = estimate_prompt_tokens(Some(&system_prompt), &user_message);

            let (content, tool_log) = stream_step_native_tools(
                &rt,
                &client,
                &model,
                system_prompt,
                native_history.clone(),
                user_message,
                &tool_registry,
                &tx,
            );
            let _ = tx.send(agent::retry::PipelineResult::StreamDone { content, tool_log });
            let _ = tx.send(agent::retry::PipelineResult::StreamMeta {
                total_prompt_tokens: total_tokens,
                model,
            });
            return;
        }

        let total_steps = steps.len();
        tracing::info!(
            "executing {} steps from plan ({} bytes)",
            total_steps,
            plan.len()
        );
        let mut all_content = String::new();
        let mut all_tool_log = String::new();
        let mut step_results: Vec<String> = Vec::new();
        let per_step_budget = context_window_limit / (4 * total_steps.max(1) as u64);
        let system_prompt = format!(
            "{}\n\nWorking directory: {}\nCurrent date: {}\nOutput limit for this step: keep response under {} tokens ({} lines max). Output ONLY the current step — do not attempt other steps.",
            coding_system,
            workspace.display(),
            now,
            per_step_budget,
            per_step_budget / 4,
        );

        for (i, step_desc) in steps.iter().enumerate() {
            let step_num = i + 1;

            let _ = tx.send(agent::retry::PipelineResult::StepStart {
                step: step_num,
                total: total_steps,
                description: step_desc.clone(),
            });

            // Note: `[SEARCH]` plan steps were previously special-cased to invoke
            // run_web_search directly. That behavior is now subsumed by native tool
            // calling: the LLM emits a `web_search` tool call and `stream_step_native_tools`
            // dispatches it via the ToolRegistry.

            let prev_summary = if step_results.is_empty() {
                String::new()
            } else {
                let mut s = "\n\n[Previous steps completed]\n".to_string();
                for (j, result) in step_results.iter().enumerate() {
                    // Extract file paths from previous results for quick reference
                    let file_paths: Vec<&str> = result
                        .lines()
                        .filter(|l| l.trim().starts_with("### FILE:"))
                        .map(|l| l.trim().trim_start_matches("### FILE:").trim())
                        .collect();
                    if !file_paths.is_empty() {
                        s.push_str(&format!(
                            "Step {}: {} → files: {}\n",
                            j + 1,
                            steps.get(j).map(|s| s.as_str()).unwrap_or("(completed)"),
                            file_paths.join(", ")
                        ));
                    } else {
                        // Non-file result (search, command output, etc.) — include short summary
                        let preview: String = result.chars().take(500).collect();
                        s.push_str(&format!(
                            "Step {}: {} → {}\n",
                            j + 1,
                            steps.get(j).map(|s| s.as_str()).unwrap_or("(completed)"),
                            preview
                        ));
                    }
                }
                s.push_str("\nIMPORTANT: Read any files from previous steps before proceeding. Files listed above contain the actual content from those steps.\n");
                s
            };

            let user_msg = format!(
                "Original request: {}\n\nPlan:\n{}\n{}Now execute ONLY step {} of {}: {}\n\n\
                 Workflow for this step:\n\
                 1. If previous steps created files, READ them first to recall their content\n\
                 2. Use tools (exec_shell, read_file, web_reader, web_search, ...) as needed \
                 for this step\n\
                 3. If this step requires creating or modifying a file, output it using the \
                 format below; otherwise skip the file format\n\
                 4. End the step when its work is done. You do NOT need to write a prose \
                 summary or a \"final answer\" — a later Eval step reviews the whole execution \
                 and writes the concise answer the user sees.\n\n\
                 Output a file ONLY when a file change is needed, using this format:\n\
                 ### FILE: relative/path/to/file\n\
                 ### ACTION: create|modify\n\
                 ```\nfile content\n```",
                input,
                plan,
                prev_summary,
                step_num,
                total_steps,
                step_desc,
            );

            let (content, step_tool_log) = stream_step_native_tools(
                &rt,
                &client,
                &model,
                system_prompt.clone(),
                native_history.clone(),
                user_msg.clone(),
                &tool_registry,
                &tx,
            );

            tracing::info!(
                "step {}/{} complete: {} bytes, {} lines",
                step_num,
                total_steps,
                content.len(),
                content.lines().count()
            );

            if content.starts_with("ERROR:") {
                let _ = tx.send(agent::retry::PipelineResult::Retry(
                    agent::retry::RetryResult::Failed {
                        last_error: content,
                        attempts: step_num,
                    },
                ));
                return;
            }

            all_content.push_str(&content);
            all_content.push('\n');
            all_tool_log.push_str(&step_tool_log);
            step_results.push(content);
        }

        // Final StreamMeta: token estimate for the last step's prompt.
        let total_tokens = estimate_prompt_tokens(Some(&system_prompt), &input);

        tracing::info!(
            "all {} steps complete: total {} bytes, {} lines",
            total_steps,
            all_content.len(),
            all_content.lines().count()
        );
        let _ = tx.send(agent::retry::PipelineResult::StreamDone {
            content: all_content,
            tool_log: all_tool_log,
        });
        let _ = tx.send(agent::retry::PipelineResult::StreamMeta {
            total_prompt_tokens: total_tokens,
            model,
        });
    });
}


/// Maximum number of tool-call rounds within a single plan step. Each round is one
/// `/api/chat` call. Five rounds covers a reasonable fetch→inspect→decide sequence
/// without risking runaway loops.
const MAX_TOOL_ROUNDS_PER_STEP: usize = 5;

/// Execute one plan step via Ollama's native tool-calling (`tools=` on `/api/chat`).
///
/// Loops: call `/api/chat` with the tool definitions → if the model returns native
/// tool calls, dispatch the first via the `ToolRegistry`, append the assistant turn
/// (with its `tool_calls`) and the `tool`-role result to the message history, and
/// re-call so the model sees the result and continues. Terminates when the model
/// returns no tool calls (the step's content becomes exec output for the Eval
/// step) or `MAX_TOOL_ROUNDS_PER_STEP` is hit.
///
/// Returns `(assistant_content, tool_log)`. The assistant text is the file source
/// (parsed by `parse_file_changes`); `tool_log` is a transcript of every tool call
/// dispatched this step (name, arguments, success/error, output). The Eval step and
/// the redo `[Previous attempt]` block read `tool_log` because the assistant text
/// alone is often empty for a tool-only step.
///
/// Uses `/api/chat`, which does NOT expose the KV-cache `context` handle — there is
/// no manual cache reuse on this path. The status bar's `ctx:N%` indicator is fed
/// from the rough prompt-token estimate computed by the caller.
fn stream_step_native_tools(
    rt: &tokio::runtime::Runtime,
    client: &ollama::OllamaClient,
    model: &str,
    system_prompt: String,
    history_messages: Vec<serde_json::Value>,
    user_message: String,
    tools: &tools::ToolRegistry,
    tx: &mpsc::Sender<agent::retry::PipelineResult>,
) -> (String, String) {
    let tool_defs = tools.ollama_tool_definitions();
    let mut messages: Vec<serde_json::Value> = Vec::with_capacity(history_messages.len() + 2);
    messages.push(serde_json::json!({ "role": "system", "content": system_prompt }));
    messages.extend(history_messages);
    messages.push(serde_json::json!({ "role": "user", "content": user_message }));

    let mut prev_signature = String::new();
    let mut tool_log = String::new();

    for round in 0..MAX_TOOL_ROUNDS_PER_STEP {
        let tx_chunk = tx.clone();
        let response = match rt.block_on(client.chat_native_streaming(
            model,
            messages.clone(),
            &tool_defs,
            |c: &str| {
                let _ = tx_chunk.send(agent::retry::PipelineResult::StreamChunk {
                    content: c.to_string(),
                });
            },
        )) {
            Ok(r) => r,
            Err(e) => return (format!("ERROR: Native chat failed: {}", e), tool_log),
        };

        if response.tool_calls.is_empty() {
            tracing::info!(
                "stream_step_native_tools round {}: no tool calls, step complete (chars={})",
                round,
                response.content.chars().count()
            );
            return (response.content, tool_log);
        }

        // Dispatch only the FIRST tool call (sequential agent loop — the model must
        // see a tool's result before emitting a call that depends on it).
        let tc = response.tool_calls.into_iter().next().expect("non-empty");
        let call_id = tc
            .id
            .clone()
            .unwrap_or_else(|| format!("native-{}", round));
        let signature = format!("{}:{}", tc.name, tc.arguments);
        if signature == prev_signature {
            tracing::warn!(
                "stream_step_native_tools round {}: repeating tool signature, finalizing step",
                round
            );
            return (response.content, tool_log);
        }
        prev_signature = signature;

        // Echo the assistant turn (with its tool_calls) so the model sees what it said.
        messages.push(serde_json::json!({
            "role": "assistant",
            "content": response.content,
            "tool_calls": [{
                "id": call_id,
                "type": "function",
                "function": { "name": tc.name, "arguments": tc.arguments }
            }]
        }));

        tracing::info!(
            "stream_step_native_tools round {}: dispatching tool={} args={:?}",
            round,
            tc.name,
            tc.arguments
        );
        let _ = tx.send(agent::retry::PipelineResult::ToolStart {
            tool_name: tc.name.clone(),
            call_id: call_id.clone(),
        });

        let result = if !tools.has_tool(&tc.name) {
            tools::ToolResult::err(
                &tc.name,
                &call_id,
                format!(
                    "Unknown tool '{}'. Available tools: {}",
                    tc.name,
                    tools.list_names().join(", ")
                ),
            )
        } else {
            tools
                .get(&tc.name)
                .expect("checked above")
                .execute(tc.arguments.clone(), call_id.clone())
                .unwrap_or_else(|e| {
                    tools::ToolResult::err(&tc.name, &call_id, format!("{}", e))
                })
        };
        tracing::info!(
            "stream_step_native_tools round {}: tool {} success={} output_chars={}",
            round,
            tc.name,
            result.success,
            result.output.chars().count()
        );
        let _ = tx.send(agent::retry::PipelineResult::ToolResultReady {
            result: result.clone(),
        });

        // Record the call + result in the step's tool transcript. This is what the
        // Eval step and the redo `[Previous attempt]` block read — the assistant
        // text alone is empty for a tool-only step, so without this the eval model
        // cannot see what the tools returned.
        let status = if result.success { "success" } else { "error" };
        tool_log.push_str(&format!(
            "\n[Tool: {}]\nargs: {}\nresult ({}):\n{}\n",
            tc.name, tc.arguments, status, result.output
        ));

        // Append the tool result so the model can continue.
        messages.push(serde_json::json!({
            "role": "tool",
            "name": tc.name,
            "content": result.output
        }));
    }

    tracing::warn!(
        "stream_step_native_tools: hit MAX_TOOL_ROUNDS_PER_STEP={}, returning empty content",
        MAX_TOOL_ROUNDS_PER_STEP
    );
    (String::new(), tool_log)
}

/// Token budget for auto-injected skill bodies. Keeps the prompt bounded even when
/// several skills match the user's input.
const MAX_MATCHED_SKILL_TOKENS: usize = 1500;

/// Build a "## Relevant domain rules" block from skills whose trigger keywords
/// appear in the user's input (see `SkillRegistry::match_triggers`). Returns an
/// empty string when nothing matches, so callers can cheaply no-op. Cumulative
/// body size is capped at `token_cap` (estimated) so a broad input that matches
/// many skills can't unbounded-bloat the prompt.
fn matched_skills_block(
    input: &str,
    skills: &skills::SkillRegistry,
    token_cap: usize,
) -> String {
    let matched = skills.match_triggers(input);
    if matched.is_empty() {
        return String::new();
    }
    let mut total = 0usize;
    let mut bodies: Vec<String> = Vec::new();
    for s in matched {
        let body = format!("### Skill: {} ({})\n{}", s.name, s.description, s.content);
        let cost = util::text::estimate_tokens(&body);
        if total + cost > token_cap {
            break;
        }
        total += cost;
        bodies.push(body);
    }
    if bodies.is_empty() {
        return String::new();
    }
    format!(
        "\n\n## Relevant domain rules (auto-injected from skills)\n{}",
        bodies.join("\n\n")
    )
}

/// Estimate total tokens in a generate prompt.
fn estimate_prompt_tokens(system: Option<&str>, prompt: &str) -> usize {
    let mut total = util::text::estimate_tokens(prompt);
    if let Some(sys) = system {
        total += util::text::estimate_tokens(sys);
    }
    total
}

/// Spawn a skill-based request on a background thread.
fn spawn_skill_request(
    app_state: &AppState,
    _client: &ollama::OllamaClient,
    skill: &skills::Skill,
    args: &str,
    tx: mpsc::Sender<agent::retry::PipelineResult>,
) {
    let model = app_state.config.exec_model.clone();
    if model.is_empty() {
        let _ = tx.send(agent::retry::PipelineResult::Retry(
            agent::retry::RetryResult::Failed {
                last_error: "No core model configured. Run setup or edit ~/.litepilot/config.toml"
                    .into(),
                attempts: 0,
            },
        ));
        return;
    }

    if args.is_empty() {
        let _ = tx.send(agent::retry::PipelineResult::Retry(
            agent::retry::RetryResult::Failed {
                last_error: format!("Usage: /{} <question or description>", skill.name),
                attempts: 0,
            },
        ));
        return;
    }

    // Build system prompt via PromptBuilder + skill content
    let base_prompt = app_state.prompt_builder.build();
    let system_prompt = format!("{}\n\n{}", base_prompt, skill.content);
    let max_retries = app_state.config.max_retries;
    let endpoint = app_state.config.ollama_endpoint.clone();
    let connect_timeout = app_state.config.connect_timeout;
    let context_window_limit = app_state.config.context_window_limit;
    let user_message = args.to_string();
    let kind = if skill.name == "simplify" || skill.name == "review" || skill.name == "test" {
        agent::retry::ResponseKind::CodeImplementation
    } else {
        agent::retry::ResponseKind::Chat
    };
    let think = app_state.think_enabled;

    tracing::info!(
        "spawn_skill_request: skill={}, model={}, kind={:?}, max_retries={}, think={}",
        skill.name,
        model,
        kind,
        max_retries,
        think
    );

    std::thread::spawn(move || {
        let rt = match tokio::runtime::Runtime::new() {
            Ok(rt) => rt,
            Err(e) => {
                let _ = tx.send(agent::retry::PipelineResult::Retry(
                    agent::retry::RetryResult::Failed {
                        last_error: format!("Runtime error: {}", e),
                        attempts: 0,
                    },
                ));
                return;
            }
        };

        let bg_config = config::Config {
            ollama_endpoint: endpoint,
            connect_timeout,
            context_window_limit,
            ..config::Config::default()
        };
        let bg_client = match ollama::OllamaClient::new(&bg_config) {
            Ok(c) => c,
            Err(e) => {
                let _ = tx.send(agent::retry::PipelineResult::Retry(
                    agent::retry::RetryResult::Failed {
                        last_error: format!("Client error: {}", e),
                        attempts: 0,
                    },
                ));
                return;
            }
        };

        let result = rt.block_on(agent::retry::chat_with_retry(
            &bg_client,
            &model,
            &system_prompt,
            &user_message,
            kind,
            max_retries,
            think,
        ));
        let _ = tx.send(agent::retry::PipelineResult::Retry(result));
    });
}

fn render_retry_result(ui_state: &mut ui::UiState, result: agent::retry::RetryResult) {
    let content = match &result {
        agent::retry::RetryResult::Success { content, attempts } => {
            if *attempts > 0 {
                ui_state.add_output(OutputLine::System(format!(
                    "Got valid response after {} retries",
                    attempts
                )));
            }
            content.clone()
        }
        agent::retry::RetryResult::Exhausted {
            content,
            attempts,
            corrections,
        } => {
            ui_state.add_output(OutputLine::Error(format!(
                "Response still invalid after {} retries. Showing last attempt:",
                attempts
            )));
            for (_, reason) in corrections {
                ui_state.add_output(OutputLine::Error(format!("  - {}", reason)));
            }
            content.clone()
        }
        agent::retry::RetryResult::Failed { last_error, .. } => {
            ui_state.add_output(OutputLine::Error(last_error.clone()));
            return;
        }
    };

    // Display the assistant response
    ui_state.add_output(OutputLine::Assistant(content.clone()));

    // If the response contains file changes, present them for review
    let changes = agent::parse_file_changes(&content);
    if !changes.is_empty() {
        tracing::info!(
            "retry path: detected {} file change(s) in response",
            changes.len()
        );
        for change in &changes {
            tracing::debug!(
                "  retry file: {} {} ({} bytes)",
                change.action,
                change.path.display(),
                change.content.len()
            );
        }
        ui_state.add_output(OutputLine::System(format!(
            "Detected {} file change(s):",
            changes.len()
        )));
        for change in &changes {
            let action_icon = match change.action.as_str() {
                "create" => "+",
                "modify" => "~",
                "delete" => "-",
                _ => "?",
            };
            ui_state.add_output(OutputLine::System(format!(
                "  {} {} ({})",
                action_icon,
                change.path.display(),
                change.action
            )));

            // Show diff preview for modifications
            if change.action == "modify" {
                let full_path = ui_state.workspace_hint.join(&change.path);
                if full_path.exists() {
                    if let Ok(old_content) = std::fs::read_to_string(&full_path) {
                        let diff = util::diff::generate_unified_diff(
                            &old_content,
                            &change.content,
                            &change.path.to_string_lossy(),
                        );
                        let removed: Vec<String> = diff
                            .lines()
                            .filter(|l| l.starts_with('-') && !l.starts_with("---"))
                            .map(|l| l.to_string())
                            .collect();
                        let added: Vec<String> = diff
                            .lines()
                            .filter(|l| l.starts_with('+') && !l.starts_with("+++"))
                            .map(|l| l.to_string())
                            .collect();
                        ui_state.add_output(OutputLine::Diff { added, removed });
                    }
                }
            }
        }
        ui_state.add_output(OutputLine::System(
            "Type /apply to write these files, or ignore to discard.".into(),
        ));
    }
}

/// Maximum number of eval-proposed redos allowed in a single turn. Beyond this
/// the eval step must not propose another redo (it accepts or hands control to
/// the user), so an unhappy eval cannot loop forever.
const MAX_REDOS_PER_TURN: u32 = 2;

/// Spawn the eval-model reflection over a completed execution. The eval model
/// judges whether the plan + execution satisfied the user's request, writes the
/// concise final-answer summary (the canonical assistant turn), and — when
/// unsatisfied — proposes a user-approved redo / further round.
///
/// Short-circuits (no-op) when no distinct eval model is configured.
fn spawn_eval_reflection(
    app_state: &AppState,
    user_request: &str,
    plan: &str,
    exec_output: &str,
    tool_log: &str,
    redo_count: u32,
    tx: mpsc::Sender<agent::retry::PipelineResult>,
) {
    // Eval runs whenever an eval model is explicitly configured — even if it is the
    // same model as exec (the reflection still yields a clean answer-only summary).
    // Short-circuit only when no eval model is set at all.
    let eval_model = app_state.config.eval_model.clone();
    if eval_model.is_empty() {
        return;
    }

    let endpoint = app_state.config.ollama_endpoint.clone();
    let connect_timeout = app_state.config.connect_timeout;
    let context_window_limit = app_state.config.context_window_limit;
    let user_request = user_request.to_string();
    let plan = plan.to_string();
    let redo_cap_note = if redo_count >= MAX_REDOS_PER_TURN {
        format!(
            "You have already proposed the maximum of {} redo(s) this turn. Set redo_kind \
             to \"none\" regardless of quality — do not propose another redo.",
            MAX_REDOS_PER_TURN
        )
    } else {
        String::new()
    };
    let exec_output = exec_output.to_string();
    let tool_log = tool_log.to_string();

    tracing::info!(
        "spawning eval reflection: eval_model={}, exec_output={} bytes, redo_count={}",
        eval_model,
        exec_output.len(),
        redo_count
    );

    std::thread::spawn(move || {
        let rt = match tokio::runtime::Runtime::new() {
            Ok(rt) => rt,
            Err(e) => {
                tracing::error!("eval reflection runtime error: {}", e);
                return;
            }
        };

        let bg_config = config::Config {
            ollama_endpoint: endpoint,
            connect_timeout,
            context_window_limit,
            ..config::Config::default()
        };
        let client = match ollama::OllamaClient::new(&bg_config) {
            Ok(c) => c,
            Err(e) => {
                tracing::error!("eval reflection client error: {}", e);
                return;
            }
        };

        // Truncate exec output if too long for eval context.
        let max_output_chars = 8000;
        let truncated_output = if exec_output.len() > max_output_chars {
            format!(
                "{}\n\n[...truncated, {} chars omitted]",
                &exec_output[..max_output_chars],
                exec_output.len() - max_output_chars
            )
        } else {
            exec_output.clone()
        };

        let eval_system = format!(
            "You are the EVALUATION stage of a Plan→Execute→Eval coding agent. A separate \
             executor already produced the work below. Judge whether that execution satisfies \
             the user's original request, and write the concise final answer the user sees.\n\n\
             You MUST call the `submit_evaluation` tool exactly once with:\n\
             - satisfied: true if the execution fully addresses the request; false ONLY on a \
             clear, concrete shortfall (missing file, wrong behavior, unanswered question). \
             Bias toward true — do not mark false for style, wording, or minor preferences.\n\
             - summary: the concise, answer-only response to the user. State what was done / \
             the answer directly. Do NOT include chain-of-thought, reasoning steps, or rules \
             copied from any instructions. Keep it short.\n\
             - redo_kind: \"none\" when satisfied; \"further\" for one more targeted pass with \
             a specific follow-up; \"plan\" to re-plan and re-execute from scratch. Only set \
             non-\"none\" when satisfied=false.\n\
             - redo_reason: 1-2 sentences on the concrete shortfall (empty when satisfied).\n\
             - redo_request: the exact follow-up request to run for a \"further\" redo (empty \
             otherwise).\n\n{}\n\n\
             The execution output may contain tool calls, file blocks (### FILE:), and command \
             results — treat those as the work performed. Files mentioned were already written \
             to disk.",
            redo_cap_note
        );

        // Tool-call transcript. The assistant text (exec output) is often empty for
        // a tool-only step, so this is where the concrete results live — e.g. the
        // count returned by `exec_shell`. Capped so a verbose tool can't crowd out
        // the rest of the eval context.
        let tool_results_section = if tool_log.trim().is_empty() {
            String::new()
        } else {
            let max_tool_chars = 4000;
            let tl = if tool_log.len() > max_tool_chars {
                format!(
                    "{}\n\n[...truncated, {} chars omitted]",
                    &tool_log[..max_tool_chars],
                    tool_log.len() - max_tool_chars
                )
            } else {
                tool_log.clone()
            };
            format!("Tool results (what the tools actually returned):\n{}\n\n", tl)
        };

        let eval_user = format!(
            "User request:\n{}\n\nPlan:\n{}\n\n{}Execution output:\n{}\n\n\
             Call submit_evaluation with your verdict.",
            user_request, plan, tool_results_section, truncated_output
        );

        let messages = vec![
            serde_json::json!({ "role": "system", "content": eval_system }),
            serde_json::json!({ "role": "user", "content": eval_user }),
        ];

        let eval_tool = serde_json::json!({
            "type": "function",
            "function": {
                "name": "submit_evaluation",
                "description": "Submit your evaluation: satisfaction verdict, concise final-answer summary, and (if unsatisfied) a redo proposal.",
                "parameters": {
                    "type": "object",
                    "properties": {
                        "satisfied": { "type": "boolean", "description": "true if the execution fully satisfies the request" },
                        "summary": { "type": "string", "description": "Concise answer-only summary for the user (no chain-of-thought or copied rules)" },
                        "redo_kind": { "type": "string", "enum": ["none", "further", "plan"], "description": "none=satisfied; further=one more targeted pass; plan=re-plan from scratch" },
                        "redo_reason": { "type": "string", "description": "Why unsatisfactory (1-2 sentences). Empty if satisfied." },
                        "redo_request": { "type": "string", "description": "Suggested follow-up request for a 'further' redo. Empty otherwise." }
                    },
                    "required": ["satisfied", "summary", "redo_kind"]
                }
            }
        });

        // The eval summary is delivered as one EvalReady event (not streamed — MVP).
        let response = rt.block_on(client.chat_native_streaming(
            &eval_model,
            messages,
            &[eval_tool],
            |_c: &str| {},
        ));

        let verdict = match response {
            Ok(resp) => parse_eval_verdict(&resp),
            Err(e) => {
                tracing::warn!("eval reflection failed: {}", e);
                agent::retry::EvalVerdict::satisfied(format!("[Eval] reflection failed: {}", e))
            }
        };
        let _ = tx.send(agent::retry::PipelineResult::EvalReady {
            verdict,
            model: eval_model.clone(),
        });
    });
}

/// Parse the eval model's `submit_evaluation` tool call into an `EvalVerdict`.
/// No tool call (or unparseable args) → bias to satisfied, using any text content
/// as the summary (never leaves the turn without an answer).
fn parse_eval_verdict(resp: &ollama::chat::ChatResponse) -> agent::retry::EvalVerdict {
    use agent::retry::{EvalVerdict, RedoKind, RedoProposal};
    if let Some(tc) = resp.tool_calls.first() {
        let args = &tc.arguments;
        let satisfied = args.get("satisfied").and_then(|v| v.as_bool()).unwrap_or(true);
        let summary = args
            .get("summary")
            .and_then(|v| v.as_str())
            .unwrap_or("")
            .to_string();
        let redo_kind = match args
            .get("redo_kind")
            .and_then(|v| v.as_str())
            .unwrap_or("none")
        {
            "further" => RedoKind::Further,
            "plan" => RedoKind::Plan,
            _ => RedoKind::None,
        };
        let proposal = if !satisfied && redo_kind != RedoKind::None {
            let reason = args
                .get("redo_reason")
                .and_then(|v| v.as_str())
                .unwrap_or("")
                .to_string();
            let request = args
                .get("redo_request")
                .and_then(|v| v.as_str())
                .unwrap_or("")
                .to_string();
            Some(RedoProposal {
                kind: redo_kind,
                reason,
                request,
            })
        } else {
            None
        };
        // Fall back to text content if the model gave no summary string.
        let summary = if summary.trim().is_empty() {
            resp.content.trim().to_string()
        } else {
            summary
        };
        EvalVerdict {
            satisfied,
            summary,
            proposal,
        }
    } else {
        EvalVerdict::satisfied(resp.content.trim())
    }
}

/// Push the finalized assistant answer into history + session, run compaction,
/// and trigger background summarization if warranted. Shared by the StreamDone
/// short-circuit (exec content as the answer) and EvalReady (eval summary as the
/// answer) — only one of the two runs per turn.
fn commit_assistant_answer(
    app_state: &mut AppState,
    content: &str,
    result_tx: &mpsc::Sender<agent::retry::PipelineResult>,
) {
    if content.trim().is_empty() {
        return;
    }
    let tokens = util::text::estimate_tokens(content);
    tracing::debug!("adding to conversation history: role=assistant, {} tokens", tokens);
    app_state.conversation_history.push(ConversationMessage {
        role: "assistant".into(),
        content: content.to_string(),
        tokens,
    });
    app_state.current_session.add_message("assistant", content);
    auto_save_session(app_state);
    let history_before = app_state.conversation_history.len();
    context::maybe_compact(
        &mut app_state.conversation_history,
        &app_state.config.exec_model,
    );
    if app_state.conversation_history.len() < history_before {
        tracing::info!(
            "conversation history compacted: {} -> {} messages",
            history_before,
            app_state.conversation_history.len()
        );
    }
    if app_state.conversation_summary.is_none() || app_state.conversation_history.len() > 20 {
        maybe_trigger_summarization(app_state, result_tx.clone());
    }
}

/// Run an eval-proposed redo: build a new request carrying a condensed
/// `[Previous attempt]` block, bump the redo counter, and spawn the next
/// Plan→Execute→Eval cycle.
fn run_eval_redo(
    app_state: &mut AppState,
    client: &ollama::OllamaClient,
    ui_state: &mut ui::UiState,
    proposal: agent::retry::RedoProposal,
    result_tx: mpsc::Sender<agent::retry::PipelineResult>,
) {
    use agent::retry::RedoKind;
    let base_request = match &proposal.kind {
        RedoKind::Further if !proposal.request.trim().is_empty() => proposal.request.clone(),
        // Plan redo, or a Further redo with no concrete request: re-run the original.
        _ => app_state.last_user_request.clone().unwrap_or_default(),
    };
    let prior = build_previous_attempt_block(app_state, &proposal);
    let redo_input = if prior.trim().is_empty() {
        base_request
    } else {
        format!("{}\n\n{}", base_request, prior)
    };

    app_state.redo_count = app_state.redo_count.saturating_add(1);
    ui_state.add_output(OutputLine::System(format!(
        "Running proposed redo ({}/{})…",
        app_state.redo_count, MAX_REDOS_PER_TURN
    )));
    ui_state.add_output(OutputLine::User(redo_input.clone()));
    app_state.conversation_history.push(ConversationMessage {
        role: "user".into(),
        content: redo_input.clone(),
        tokens: util::text::estimate_tokens(&redo_input),
    });
    ui_state.last_user_input = redo_input.clone();
    ui_state.start_thinking_phase("planning");
    spawn_request_for_mode(app_state, client, &redo_input, result_tx);
    app_state.is_processing = true;
}

/// Build a condensed `[Previous attempt]` context block from the stashed plan +
/// exec output and the eval's rationale, to inject into a redo request.
fn build_previous_attempt_block(
    app_state: &AppState,
    proposal: &agent::retry::RedoProposal,
) -> String {
    let mut s =
        String::from("[Previous attempt — improve on it; do not repeat the same mistakes]\n");
    if let Some(plan) = &app_state.last_plan {
        if !plan.trim().is_empty() {
            s.push_str(&format!("Previous plan:\n{}\n\n", plan));
        }
    }
    if let Some(exec) = &app_state.last_exec_output {
        if !exec.trim().is_empty() {
            let max = 2000usize;
            let preview: String = exec.chars().take(max).collect();
            let ellipsis = if exec.chars().count() > max {
                "\n[…truncated]"
            } else {
                ""
            };
            s.push_str(&format!(
                "Previous execution (condensed):\n{}{}\n\n",
                preview, ellipsis
            ));
        }
    }
    // The tool transcript usually carries the concrete results the previous
    // attempt produced (command output, read-file contents, etc.) — without it a
    // redo is blind to what the tools returned and repeats the same blind work.
    if let Some(tl) = &app_state.last_exec_tool_log {
        if !tl.trim().is_empty() {
            let max = 2000usize;
            let preview: String = tl.chars().take(max).collect();
            let ellipsis = if tl.chars().count() > max {
                "\n[…truncated]"
            } else {
                ""
            };
            s.push_str(&format!(
                "Previous tool results:\n{}{}\n\n",
                preview, ellipsis
            ));
        }
    }
    if !proposal.reason.trim().is_empty() {
        s.push_str(&format!(
            "Why it was unsatisfactory: {}\n",
            proposal.reason.trim()
        ));
    }
    s
}

/// Whether the current turn is fully complete — no LLM work in flight and no
/// approval (redo / plan / file-confirmation) pending. Gates draining the
/// pending input queue so messages never interleave with a pending eval or
/// approval.
fn turn_is_complete(app_state: &AppState) -> bool {
    !app_state.is_processing
        && app_state.pending_redo_decision.is_none()
        && app_state.pending_plan.is_none()
        && !app_state.awaiting_confirmation
}

fn spawn_request_for_mode(
    app_state: &mut AppState,
    client: &ollama::OllamaClient,
    input: &str,
    tx: mpsc::Sender<agent::retry::PipelineResult>,
) {
    // Pre-turn snapshot (non-fatal)
    if let Err(e) = app_state.snapshot_manager.pre_turn(input) {
        tracing::debug!("pre-turn snapshot skipped: {}", e);
    }

    // Emit structured event
    app_state.event_sink.turn_started(
        &app_state.config.exec_model,
        &app_state.mode.to_string(),
        input.len(),
    );

    // Update PromptBuilder with current environment before spawning
    app_state
        .prompt_builder
        .update_environment(prompt::EnvironmentBlock::capture(&app_state.workspace));
    app_state.prompt_builder.set_volatile(
        app_state.working_set.summary(),
        app_state.conversation_summary.clone(),
    );
    // Set the current goal from user input — re-injected at prompt edges for small models
    app_state.prompt_builder.set_current_goal(input);

    tracing::info!(
        "request routing: mode={}, pipeline=plan_then_execute (single-path architecture)",
        app_state.mode,
    );
    tracing::debug!("input for routing: {:?}", input);

    // Single execution pipeline: plan-then-execute handles every request, including
    // tool-using ones. The planner sees tool descriptions in its prompt; the executor
    // parses text-format <tool_call> blocks and dispatches via ToolRegistry. Auto/Plan/
    // Edit modes all flow through here, with mode-specific behavior enforced inside
    // spawn_plan_then_execute / spawn_execution_with_plan.
    spawn_plan_then_execute(app_state, client, input, tx);
}

/// Handle /run <command> — execute a shell command via the sandbox.
/// Returns current date and time as a human-readable string for LLM context.
fn current_datetime() -> String {
    chrono::Local::now().format("%Y-%m-%d %H:%M %A").to_string()
}

/// Replace {MAX_LINES} placeholder in prompts with the configured limit.
/// Check if conversation summarization is needed and spawn a background task.
fn maybe_trigger_summarization(
    app_state: &AppState,
    tx: mpsc::Sender<agent::retry::PipelineResult>,
) {
    let context_window = app_state.config.context_window_limit as usize;
    if !agent::summarizer::needs_summarization(
        &app_state.conversation_history,
        context_window,
        &app_state.summarizer_config,
    ) {
        return;
    }

    let exec_model = app_state.config.exec_model.clone();
    if exec_model.is_empty() {
        return;
    }

    let endpoint = app_state.config.ollama_endpoint.clone();
    let connect_timeout = app_state.config.connect_timeout;
    let context_window_limit = app_state.config.context_window_limit;
    let history = app_state.conversation_history.clone();
    let config = app_state.summarizer_config.clone();

    tracing::info!("spawning background summarization task");
    std::thread::spawn(move || {
        let rt = match tokio::runtime::Runtime::new() {
            Ok(rt) => rt,
            Err(e) => {
                tracing::error!("summarization runtime error: {}", e);
                return;
            }
        };
        let bg_config = config::Config {
            ollama_endpoint: endpoint,
            connect_timeout,
            context_window_limit,
            ..config::Config::default()
        };
        let client = match ollama::OllamaClient::new(&bg_config) {
            Ok(c) => c,
            Err(e) => {
                tracing::error!("summarization client error: {}", e);
                return;
            }
        };
        match rt.block_on(agent::summarizer::summarize(
            &client,
            &exec_model,
            &history,
            &config,
        )) {
            Ok(result) => {
                let _ = tx.send(agent::retry::PipelineResult::SummaryReady {
                    summary: result.summary,
                    summarized_count: result.summarized_count,
                });
            }
            Err(e) => {
                tracing::warn!("summarization failed (non-fatal): {}", e);
            }
        }
    });
}

fn apply_prompt_limits(prompt: &str, max_file_lines: usize) -> String {
    prompt.replace("{MAX_LINES}", &max_file_lines.to_string())
}

/// Substitute `{MAX_LINES}` and `{TOOLS}` placeholders in a planner system prompt.
/// `{TOOLS}` is the prose listing of available tools (name + description per line)
/// from `ToolRegistry::descriptions_text()`. Kept as a sibling to
/// `apply_prompt_limits` so callers that don't need tool interpolation are unaffected.
fn apply_plan_prompt(prompt: &str, max_file_lines: usize, tools_description: &str) -> String {
    apply_prompt_limits(prompt, max_file_lines).replace("{TOOLS}", tools_description)
}

fn handle_run_command(app_state: &mut AppState, ui_state: &mut ui::UiState, cmd: &str) {
    if cmd.is_empty() {
        ui_state.add_output(OutputLine::Error("Usage: /run <command>".into()));
        return;
    }

    if !app_state.mode.can_execute_command() {
        ui_state.add_output(OutputLine::Error(
            "Command execution not allowed in Plan mode.".into(),
        ));
        return;
    }

    // Parse command into binary + args
    let parts: Vec<String> = cmd.split_whitespace().map(String::from).collect();
    if parts.is_empty() {
        ui_state.add_output(OutputLine::Error("Empty command.".into()));
        return;
    }

    let sandbox = sandbox::Sandbox::new(app_state.workspace.clone());
    let executor = sandbox::executor::Executor::new(&sandbox);

    let bin = parts[0].clone();
    let args: Vec<String> = parts[1..].to_vec();

    // Validate command against sandbox rules
    if let Err(e) = sandbox.validate_command(&bin, &args) {
        ui_state.add_output(OutputLine::Error(format!("Blocked: {}", e)));
        return;
    }

    tracing::info!("run: {} {}", bin, args.join(" "));
    ui_state.add_output(OutputLine::System(format!(
        "Running: {} {}",
        bin,
        args.join(" ")
    )));

    let result = std::thread::scope(|s| {
        s.spawn(|| {
            let rt = tokio::runtime::Runtime::new().ok()?;
            rt.block_on(executor.run(&bin, &args, None)).ok()
        })
        .join()
        .ok()?
    });

    match result {
        Some(output) => {
            if output.success {
                tracing::info!(
                    "run success: {} {} (exit=0, stdout={} bytes)",
                    bin,
                    args.join(" "),
                    output.stdout.len()
                );
                if !output.stdout.is_empty() {
                    ui_state.add_output(OutputLine::System(output.stdout.trim_end().to_string()));
                }
                ui_state.add_output(OutputLine::System("Done.".into()));
            } else {
                tracing::warn!(
                    "run failed: {} {} (exit={:?})",
                    bin,
                    args.join(" "),
                    output.exit_code
                );
                ui_state.add_output(OutputLine::Error(format!(
                    "Exit {}: {}",
                    output.exit_code.unwrap_or(1),
                    if output.stderr.is_empty() {
                        output.stdout.trim_end()
                    } else {
                        output.stderr.trim_end()
                    }
                )));
            }
        }
        None => {
            tracing::error!("run failed: {} {} (thread panicked)", bin, args.join(" "));
            ui_state.add_output(OutputLine::Error("Failed to execute command.".into()));
        }
    }
}

/// Parse ```bash ... ``` blocks from LLM response content.
fn parse_bash_blocks(content: &str) -> Vec<String> {
    let mut commands = Vec::new();
    let mut in_bash = false;
    let mut buffer = String::new();

    for line in content.lines() {
        let trimmed = line.trim();
        if in_bash {
            if trimmed == "```" {
                in_bash = false;
                let cmds = buffer.trim().to_string();
                if !cmds.is_empty() {
                    commands.push(cmds);
                }
                buffer.clear();
            } else {
                // Skip comment-only lines
                let stripped = trimmed.trim_start_matches('#').trim();
                if !stripped.is_empty() && !trimmed.starts_with('#') {
                    buffer.push_str(trimmed);
                    buffer.push('\n');
                }
            }
        } else if trimmed == "```bash" || trimmed == "```sh" || trimmed == "```shell" {
            in_bash = true;
            buffer.clear();
        }
    }

    commands
}

/// Execute bash blocks extracted from the LLM response.
/// Uses `/bin/sh -c` so shell features (redirects, pipes, heredocs) work correctly.
fn execute_bash_blocks(app_state: &AppState, ui_state: &mut ui::UiState, content: &str) {
    let blocks = parse_bash_blocks(content);
    if blocks.is_empty() {
        return;
    }

    tracing::info!("auto-executing {} bash block(s) in Auto mode", blocks.len());

    let sandbox = sandbox::Sandbox::new(app_state.workspace.clone());

    for block in &blocks {
        // Validate the first command word in each line against sandbox rules
        for cmd_line in block.lines() {
            let cmd_line = cmd_line.trim();
            if cmd_line.is_empty() {
                continue;
            }
            let first_word = cmd_line.split_whitespace().next().unwrap_or("");
            if let Err(e) = sandbox.validate_command(first_word, &[]) {
                ui_state.add_output(OutputLine::Error(format!("Blocked: {} — {}", cmd_line, e)));
                continue;
            }
        }

        ui_state.add_output(OutputLine::System(format!("$ {}", block.lines().next().unwrap_or(""))));

        // Run the entire block through a shell so redirects/pipes/heredocs work
        let workspace = app_state.workspace.clone();
        let block_owned = block.to_string();
        let result = std::thread::scope(|s| {
            s.spawn(|| {
                let output = std::process::Command::new("/bin/sh")
                    .arg("-c")
                    .arg(&block_owned)
                    .current_dir(&workspace)
                    .output();
                output.ok()
            })
            .join()
            .ok()?
        });

        match result {
            Some(output) => {
                let stdout = String::from_utf8_lossy(&output.stdout).trim_end().to_string();
                let stderr = String::from_utf8_lossy(&output.stderr).trim_end().to_string();
                if output.status.success() {
                    if !stdout.is_empty() {
                        ui_state.add_output(OutputLine::System(stdout));
                    }
                } else {
                    ui_state.add_output(OutputLine::Error(format!(
                        "Exit {}: {}",
                        output.status.code().unwrap_or(1),
                        if stderr.is_empty() { &stdout } else { &stderr }
                    )));
                }
            }
            None => {
                ui_state.add_output(OutputLine::Error(format!("Failed: {}", block)));
            }
        }
    }
}

/// Write a FileChange to disk, with sandbox validation.
/// Run web search and return formatted context string.
/// Returns empty string if search fails or is disabled.
///
/// Unused: web search now flows through the native `web_search` tool instead of
/// a pipeline event; retained for a future non-tool caller.
#[allow(dead_code)]
async fn run_web_search(query: &str, max_tokens: usize) -> String {
    tracing::info!("web search: query={:?}, max_tokens={}", query, max_tokens);
    let config = config::Config::default();
    let engine = search::SearchEngine::new(&config);
    match engine.search(query, max_tokens).await {
        Ok(results) if !results.is_empty() => {
            tracing::info!("web search returned {} result(s)", results.len());
            search::format_search_context(&results)
        }
        Ok(_) => {
            tracing::warn!("web search returned 0 results for query={:?}", query);
            String::new()
        }
        Err(e) => {
            tracing::warn!("web search failed for query={:?}: {}", query, e);
            String::new()
        }
    }
}

/// Handle /uv subcommands: init, venv, add <pkg>, run <script>.
fn handle_uv_command(app_state: &mut AppState, ui_state: &mut ui::UiState, args: &str) {
    tracing::info!("uv command: {:?}", args);
    if !project::uv::UvManager::is_available() {
        ui_state.add_output(OutputLine::Error(
            "uv is not installed. Install it: https://docs.astral.sh/uv/".into(),
        ));
        return;
    }

    if !app_state.mode.can_execute_command() {
        ui_state.add_output(OutputLine::Error(
            "Command execution not allowed in Plan mode.".into(),
        ));
        return;
    }

    let (subcmd, rest) = match args.split_once(' ') {
        Some((s, r)) => (s, r.trim()),
        None => (args, ""),
    };

    let sandbox = sandbox::Sandbox::new(app_state.workspace.clone());
    let workspace = app_state.workspace.clone();

    let result = match subcmd {
        "init" => {
            ui_state.add_output(OutputLine::System("Running uv init...".into()));
            std::thread::scope(|s| {
                s.spawn(|| {
                    let rt = tokio::runtime::Runtime::new().ok()?;
                    rt.block_on(project::uv::UvManager::init(&workspace, &sandbox))
                        .ok()
                })
                .join()
                .ok()?
            })
        }
        "venv" => {
            ui_state.add_output(OutputLine::System("Running uv venv...".into()));
            std::thread::scope(|s| {
                s.spawn(|| {
                    let rt = tokio::runtime::Runtime::new().ok()?;
                    rt.block_on(project::uv::UvManager::create_venv(&workspace, &sandbox))
                        .ok()
                })
                .join()
                .ok()?
            })
        }
        "add" => {
            if rest.is_empty() {
                ui_state.add_output(OutputLine::Error("Usage: /uv add <package>".into()));
                return;
            }
            ui_state.add_output(OutputLine::System(format!("Running uv add {}...", rest)));
            std::thread::scope(|s| {
                s.spawn(|| {
                    let rt = tokio::runtime::Runtime::new().ok()?;
                    rt.block_on(project::uv::UvManager::add(&workspace, rest, &sandbox))
                        .ok()
                })
                .join()
                .ok()?
            })
        }
        "run" => {
            if rest.is_empty() {
                ui_state.add_output(OutputLine::Error("Usage: /uv run <script>".into()));
                return;
            }
            ui_state.add_output(OutputLine::System(format!("Running uv run {}...", rest)));
            std::thread::scope(|s| {
                s.spawn(|| {
                    let rt = tokio::runtime::Runtime::new().ok()?;
                    rt.block_on(project::uv::UvManager::run(&workspace, rest, &sandbox))
                        .ok()
                })
                .join()
                .ok()?
            })
        }
        _ => {
            ui_state.add_output(OutputLine::Error(format!(
                "Unknown /uv subcommand: {}. Use: init, venv, add, run",
                subcmd
            )));
            return;
        }
    };

    match result {
        Some(output) => {
            if output.success {
                if !output.stdout.is_empty() {
                    ui_state.add_output(OutputLine::System(output.stdout));
                }
                ui_state.add_output(OutputLine::System("Done.".into()));
            } else {
                ui_state.add_output(OutputLine::Error(format!(
                    "uv {} failed: {}",
                    subcmd,
                    if output.stderr.is_empty() {
                        &output.stdout
                    } else {
                        &output.stderr
                    }
                )));
            }
        }
        None => {
            ui_state.add_output(OutputLine::Error("Failed to execute uv command.".into()));
        }
    }
}

